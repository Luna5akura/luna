昨日の夜遅く、エレノアナは一人でこっそりとホテルから抜け出した。

真夜中に水着を着るなんて変な感じ。

温かい夏とは言え、夜風は少しだけ冷え込む。上着を一枚持ってくれば良かったとエレノアナは少し後悔した。
眼の前では夜の海が銀色に輝いていた。まるで月を海底に閉じ込めてしまったみたいだ。一人海岸線に立つエレノアナはそんなことをぼんやりと考える。

空には丸い月が浮かんでいる。まだ満月ではないらしいけれど、十分に大きくて丸い。

でもそんな夜空の月が霞んでしまうほどに海面がキラキラと美しく輝いていた。

――昼間、こんな噂を聞いた。

好きな人がいる女の子たちの間で密かに伝えられている噂だ。教えてくれたのは島に住んでいる綺麗なお姉さんだった。
真夜中の月光珊瑚礁に潜ると、運が良ければ人魚姫に出会えるらしい。
彼女は海の国のお姫様。

賢くて、色々な事を知っている。恋の悩みには特に詳しい。

エレノアナはせっかく聞いたその話をイクスとレイラにしなかった。マテリアルには関係なさそうな話だったこともあるけれど、心のなにかが言葉をつっかえさせていた。

そして何故か、誘われるように夜の海の淵にこっそりと一人で訪れていた。
危ないかもしれないとは確かに考えた。人魚たちに関して怖い噂もいくつかあったから。満月に海に入った人間を引きずり込んでしまうとか、そういう。

「でも今日は満月じゃないから……きっと、大丈夫」

寄せては返す波に素足を差し込む。冷たい……けれど覚悟していたほどではない。
なんだか海の中の方がやや暖かいくらいだった。

一歩一歩、波の奥へと進むたびに足が浸る水位が上がっていく。太ももに波の揺れを感じる頃になって、エレノアナはようやく大きく息を吸い込んだ。

こういうのは勢いが大事だ。

頭までザブンと全身を海に潜らせる。エレノアナの長い緑髪が水の中でゆらりゆらりと揺れる。視界の邪魔になった自分の髪をかき分けると、目の前を黄色い熱帯魚が横切っていった。

ここの魚たちは人に対する警戒心が薄いようだった。続いて赤、緑、青と様々な小魚たちがヒレを横切らせていく。

そして砂の海底を銀色の珊瑚が優しく照らしている。水の中で陽炎のように銀色の炎が揺れているみたいだった。その丸い炎明がいくつもいくつも重なって……たくさんのロウソクが不思議な光を灯しているみたい。海の中なのにとても暖かい。

人魚姫の宮殿、なんて言われるのも納得の光景だった。まるで現実世界じゃないみたいに幻想風景にエレノアナはしばらく見とれていた。

だけど結局、どれほど待ってみても人魚姫は訪れなかった。
水底で響いていた不思議な音色だけが唯一の収穫だった。



「バカなの？」

エレノアナの話を聞き終わったシキが半眼で吐き捨てた。

「うぅ……何も言い返せません……」

「そもそも人魚なんているわけないでしょ。おとぎ話の読みすぎよ」

「ま、マテリアルがあるなら人魚さんもいるかもしれないじゃないですか……！」

「いない」

「そんなぁ……」

「――ええ、まあ。月光珊瑚が光っている理屈は科学的に証明されていないから、ファンタジーの入り込む余地はあるけど。でも、可能性は１％より低い。既存理論上では民俗伝承に残っている女神とやらが実在する可能性と同じ――」

シキはそこまで言って、気付いた。
エレノアナたちは様々な不可思議なものにこれまで出会ってきた。

「……そう言えば実在してたわね、女神って」

「なので人魚姫様もきっといます！！」

「ああ、もう分かったわよ。それはもう否定しないから……何があったのよ。恋の悩みなんて。今さらイクスのことで悩むことなんてあったの？」

「ええっ！？私シキさんに言いましたっけ、その……」

「見ていれば分かるわ。分からないあの男が子供なだけ」

あんな見た目のクセになんでそういうところだけ、ガ……ああ、もう。
シキは恨めしそうに吐き捨ててから、はっとしたように頭を振った。

「で？」

ツン、と顎を尖らせてエレノアナを促す。
エレノアナは迷いながらもゆっくりと口を開いた。

「最近……レイラさんとイクスさんの仲が良くて嬉しいんです」

「はぁ？」

シキの心底呆れきった声が海岸線に響き渡った。

「ち、違うんです！いえっ、違わないんですけど！！その、最近イクスさんがなんか……えっと。レイラさんの前でたまに……」

可愛くって。
両手を頬にあてて、エレノアナはようやくぼそっと打ち明けた。

「でも、私イクスさんの事が好きなんです。そのはずだったんです。なので、レイラさんに取られちゃう！悔しい！！とか……いつかあるかな、って……恋のライバルってそういうことするんだよね、って思って……いて……」

「………………なかったの？」

「なかったんです……」

エレノアナはしゅん、とうなだれた。

「もしお二人が海辺の綺麗な教会で結婚式ってことになっても祝福できちゃうな、って思ったんです」

「エレノアナ、話を色々すっ飛ばしすぎよ」

「でもそう思ったんです！！レイラさんのウェディングドレスも見たいし、裾を持つのは私じゃないと嫌です！！」

「そ、そうなの……」

エレノアナの勢いにシキは少しのけぞった。
良くわからないけれど、本気であることだけは伝わってくる気迫だった。

「私、レイラさんとイクスさんが幸せになるって思ったらワクワクして、嬉しくって……ちょっとだけ寂しいけど、でも……すごく素敵な事だと思ったんです」

寂しいのは、初恋が破れるからではない。エレノアナは自分の胸に手を当てて、眉尻を下げる。
今、三人で続けている旅の形が変わってしまう気がしたからだった。

元々、この旅にはエレノアナが無理を言って付いてきた。危険なこともあるから、イクスは最初あまり良い顔をしなかったのだ。今もエレノアナはイクスとレイラに心配されてばかりで、危ない時はあまり力になれない。
それでもエレノアナにできることはあるけれど――どうして、満足できないんだろう。

自分が何でもできる神様じゃないことは分かっているのに、何もできてない無力感があって、自分が旅に付いていく理由はどこにもないんじゃあないかとたまに思えてしまう。

三人でかけがえのない仲間。

過ごしてきた時間がそれを証明してくれていることは分かっているはずなのに。

イクスとレイラが特別な仲になったら、エレノアナは身を引いて、旅から外れた方が良いのかもしれない。
そう思ってしまうことが、ほんのちょっとだけ寂しい。

ただ、それだけ。

「……手放すことは思ったよりも簡単なんです。きっと」

そうしたらエレノアナは、後は未来にワクワクするだけだ。
今感じているワクワクに身を委ねるだけでいい。世界はいつだって輝いていて、自分の大切な人たちが幸せになったらもっと明るい。

「でも。そうすると私の胸の中自身にあるキラキラとしていたものが、いなくなってしまう気がしたんです。ずっと、私の世界を明るくしてくれていたもの。……一番傷ついていた時に、私の胸にいつの間にか宿っていたもの。それをここで手放すことは……それは、寂しい事な気がして……」

言葉がうまくまとまらない。
喋れば喋れるほど違うことを言ってしまっている気がして、エレノアナはついに俯いて口を閉ざした。
それをじっと見つめていたシキが一言、ポツリと漏らす。

「ガキね」

「へっ！？」

「あ、言っちゃった。ああもう。貴方もイクスも全然大人じゃないのね。羨ましいわ」

「え、えっと……私は今シキさんに褒められた……のでしょうか？」

「安心して、褒めてないから。でも羨ましいのは本当よ」

シキは辟易したように顔をしかめている。
だがエレノアナを見つめる目はどこか優しかった。

「恋に恋してたって気付いちゃったのね。大人の恋じゃないかもしれないって」

「そう……かもです。私が恋心だと思ってたものがもしかしたら、違う何かのような気がしてて。それが悲しいとか、はないんですけれど。……迷子になっちゃった気分です」

恋ってなんだろう。

……愛って、なんだろう。

ぽつりとこぼれ出た言葉。それがなんだかエレノアナの胸にようやくしっくりと来た。

自分の気持ちにどう名前をつけたら良いかが分からなくなって……そのままどう扱ったら良いのかさえも分からなくなってしまった。
たぶん、そういうことだった。

「あーーっ、もう！！！」

シキが急にくしゃくしゃと自分の髪をかき乱し始めたのでエレノアナはびっくりした。
目を見開いているエレノアナの前でシキががくりとうなだれてしまう。

「なんで私がこんな甘酸っぱい話に巻き込まれてるのよ！！青春なんてないうちに、こんなになってた、私が！！！」

「し、シキさん？ご、ごめんなさい変な話を聞かせて――」

「今のは私自身の人生への文句！！……話を聞くと言ったのは私よ。はぁ……本当に、レクトシティ以来ツイてないわ……」

深い深いため息を一つ。
それからシキは嘆息と共に言葉を吐き出した。

「気持ちの形に正解なんてないでしょ。貴方はそのままで良いんじゃない」

「正解、ですか？」

「要するに、ライバル心が湧かない恋心は恋じゃないって考え始めちゃったんでしょ。嫉妬がない愛情は乙女の恋じゃない、って。レイラは正反対で嫉妬深そうよね。くくっ、澄ました顔してメラメラ燃えてるタイプ」

「し、シキさん？」

「ああ、ごめんなさい。同じ業界の研究者同士、色々思うところがあって」

歪んだ口元をさっと元に戻して、シキは小さな咳払いをした。

「エレノアナ、貴方は二人をどっちも心から大切にしてる。ただそれだけの事じゃないの？まあ人間かなんかよりは天使みたいな考え方だけど。貴方らしいんじゃない」

「でも……」

「それとも。いつか大切な人に本気で嫉妬してしまいそうで怖い？」

「……どんなに考えても、そうならない気がするんです。だから……私は……」

「恋なんて元からしてなかった、って？」

「……………」

「そうじゃないでしょ、エレノアナ。そうやって自分を押し殺して、色のない世界で生きていくつもり？……貴方はそうじゃないでしょ、エレノアナ」

シキの手が伸びた。
エレノアナの頬に白い手が触れる。氷のように冷たい手だが、手付きは不器用で、優しかった。

「嫉妬はできない。でも好きな人はいる。そうね、おかしいって言う人はたしかに何人もいるかもね。それは恋なんかじゃないって。……でも、貴方が恋と名付けたなら、それで良いのよ。自分で不安になる時は私が認めてあげる。貴方は立派に恋をしているわ。……友達の言葉なら信じてくれるでしょ」

「良いんでしょうか」

「持っていちゃいけない気持ちなんてあるの？」

シキはおかしそうにくすくすと笑った。

「手放しがたいなら、きっとそれは貴方にとって必要なものよ。他の人とどれだけ違う形をしていても、なんだか奇っ怪なもののように思えても。良いじゃない、珍しいもの。大事に持っておきなさい。――まっ、叶うかどうかは別だけどね」

エレノアナの頬からパッと手を離したシキが肩をすくめる。

「か、叶わない……」

ショックを受けたまま固まってしまったエレノアナを見て、シキは吹き出した。

「良く分からない子ね。――でもそれでいい。エレノアナ、貴方の胸の中には虹が眠っている。他の人には持ちえない、無数の色がある。……そういうとこに救われてるのよ。少なくとも、私と、彼はね」

「彼？」

「あなたの勝算はそこまで低くない、ってこと」

だって、戦ってる人はいつだって眩しいんだから。
そう言って、シキは微笑んだ。
氷が溶けた雪解け水のように暖かな笑顔だった。
