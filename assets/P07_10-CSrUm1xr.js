「様子がおかしかったあいつらは……あの赤い光に、マテリアルに操られていたのか？」
「さあ。分からないわ。関係しているとは思うけれど、私たちもそこまで突き止められていないの。詳しいことは戻ってから聞きなさいな」
　ティアラがイクスの胸をトン、と押す。
　気付けば深い穴があった。重力に引かれるまま、落下していくイクス。下へ向かえば向かうほど、何か奇妙な“音”が近付いてくる。先ほどまでイクスを包んでいた子守歌とは違う、別の“音”だ。
暗くて深い穴の底に落ちていく螺旋階段。その麓にあるカタコンベ墓場から奏でられる不気味で美しい音色。だけど、それは以前聞いたときよりもどこか軽快で、無邪気にも思えた。
