臼倉峠の山頂の休憩スポットに到着すると、すでに多くの車や観衆が集まっており、賑わいを見せていた。車のほとんどがドライブユーフォリアのメンバーのものだとすぐにわかった。観衆の中央には、リーダーのユキオとメカニック担当のダイチもいる。そして、彼らと向かい合っているシルバーヘアの男がいた。山間のカフェで見た写真の男、リョウスケだとすぐに分かった。

イクスたちは急いでキャンピングカーから降り、観衆の間を縫って進んでいく。近くに寄って耳を傾けると、リョウスケとユキオの間で激しい口論がされているようだった。

リョウスケはユキオにダウンヒルのバトルを申し込んでいるようだ。

「ユキオさん、いい加減、オレとバトルしてくださいよ」

「リョウスケ、何度も言ってるだろ。オレはもう、そういうバトルに興味がないんだ」

リョウスケは顔を歪め、強い口調でユキオに迫っていた。

「ユキオさん、オレはもう何度も申し込んでいるんです。オレはあなたと戦いたい。ドライブユーフォリアのリーダーとして、オレに勝負を挑んでください」

ユキオはリョウスケの目を見つめ、深く息を吸い込んだ。

「……わかった。でも、条件がある。オレが勝った場合、リョウスケ、お前には他のチームに対するバトルを仕掛けるのはやめてもらう。それでいいか？」

リョウスケはにっこり笑って、ユキオに向かって言い放つ。

「それで構いません。ただし、オレが勝った場合、ドライブユーフォリアは解散してもらいますよ」

ユキオは少し間をあけ大きく深呼吸した後にやさしい目に鋭い光を浮かべて、うなずいた。

「いいだろう。それなら、受けて立つ」

リョウスケは過去に走り屋のチームにバトルを申し込み、勝利した場合、そのチームに解散を迫っていたようだった。イクスたちが会話に割り込む余裕もなく、ユキオは白い車に乗り込み、リョウスケは青い車に乗り込んだ。エンジンの音が響き渡り観衆が盛り上がる中、イクスはダイチに合流しバトルを見守ることにした。

そのままバトルが開始されると、ユキオとリョウスケはダウンヒルを疾走し始めた。エンジンの轟音が夜の静寂を切り裂くように響き渡り、観衆は息をのんで見守っていた。イクスもダイチと共に、両者のスタートを目の当たりにしていた。レイラとエレノアナも興味津々で観戦していた。

「ユキオさん…勝てますよね？」

エレノアナの言葉にダイチは少し表情を変えて続けた。

「いや、たぶん、リョウスケが勝つよ。事故から退院してから、今日みたいにリョウスケが別のチームとバトルをしているのを見かけたんだけど、彼の走りは本当に異次元だったんだ。なんていうか、ドリフトでコーナーを曲がるときに物理法則を無視しているというか……うーむ、言葉にしづらいな。とにかく、リョウスケにバトルで勝つことは誰にもできないと思う。プロのレーサーでも無理かもしれないな」

イクスは驚いた様子で言った。

「そんなにリョウスケさんが強いとは……でも、ユキオさんもかなりの腕前ですよね？」

ダイチは肯定しつつも慎重に言葉を選んだ。

「そうだね、ユキオもすごい腕前だけど、正直なところリョウスケのレベルにはまだ届かないかもしれない。ただ、ユキオは絶対に負けない精神力を持っているから、最後まで戦い抜くだろうね」

エレノアナも心配そうな顔でうなずいていた。

「私たちは応援するしかないですね……」

イクスはみんなの顔を見回して、力強く言った。

「そうだね。みんなでユキオさんを応援しよう。彼がどんなに厳しい状況でも、オレたちが後ろで支えていることを感じてもらえれば、きっと彼も力を発揮できるはずだ」

ダイチはイクスの言葉に同意して頷いた。

「それに、ユキオがいつも言ってるように、バトルには勝敗だけじゃない価値がある。リョウスケにもそれを理解してもらえれば、彼のやり方も変わるかもしれない」

レイラは希望に満ちた目で言った。

「私もそう思います。最後まで信じて、ユキオさんを応援しましょう！」
