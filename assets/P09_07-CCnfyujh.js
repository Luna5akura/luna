あと８秒。

レイラの指が無音のカウントダウンと共に折りたたまれていって、イクスに突入の合図を示す。マウスピースで覆われた口元からは言葉は出てこずに、ぷくりぷくりと泡だけが漏れ出した。

水の中に潜っている間は喋れないけれど、こうして意思の疎通を図ることはできる。

準備OKです、レイラさん。イクスは心の中だけで返事をした。目線を送っただけなのに、レイラはイクスの返事が聞こえたかのようにしっかりと頷いた。

３、２、１――指でのカウントが終わると同時に重い何かが動く音がして、眼の前の金属ドアが開いていく。水中には不釣り合いなその人工扉全体に走る回路のような模様が緑に光りはじめたのは、認証が通った印だろう。レイラのハッキングが成功したのだ。

開いた先にはぽっかりと闇のような空洞が広がっていた。ちょうど人間が二人通れる程度の広さの通路だ。闇の奥から微かに、ゴゴゴ……と重々しい機械が働いている音がする。

イクスは通路の中に滑り込みながら、突入前にレイラと交わした会話を思い出していた。

『良いかしら、シケロン達は水中リニアエレベーターを移動の足に使っている。私達の目的である離島へは、そのエレベーターからしか入れない事が分かったわ』

『エレベーターには誰でも乗れる、はずがありませんよね』

レイラが小さく頷いた。手に持った端末をイクスの方に寄せて、画面に映った資料を見せる。目的地である離島やリニアエレベーターの位置を表す図をタップするといくらかの説明書きが現れた。

『ええ。シケロンの『目』がないと――虹彩認証を突破しないと、エレベーターには乗れないわ。今からそこを破るのは難しいでしょうね。出来たとしても、エレベーターを使う経路はいわば正面突破……堂々と相手の玄関口から入ることになるわ。あんまり使いたい手じゃないわね。だから――』

『整備用トンネルからリニアエレベーター通路に侵入する』

『そういうこと！』

エレベーター内部を点検するために用意された整備用トンネルの方は暗証番号でロックされている。それくらいならなんとでもなる、とレイラが得意げに笑った。

『問題は、エレベーターの通る道を生身で泳いでいかなければならないという事。泳いでいる間に、万が一エレベーターが通ってきたら……一巻の終わりね！』

『楽しそうに言わないでくださいよ……エレベーターの動きを止めることはできますか？』

妨害によって侵入の気配は察知されるかもしれないが、いつ来るかわからないエレベーターに怯えるよりはマシだった。何か手はないかと端末をいじって情報を探すイクスの指の横に、レイラの人差し指が滑り込む。ピッ、と短い電子音とともに画面が切り替わった。

『あらイクスくん、私たち気が合うわね？私もそう思っていたから……これを使おうと思うの』

端末を叩いたレイラの指がリニアエレベーターのシステム構造を表示させる。『点検用システム』。このシステムが作動している間、リニアエレベーターは完全に停止するようだ。

『こいつは毎日定期的に動いているものだし、小さい不備を発見した時もオートでこのシステムが走っている。つまり私達が侵入している間にちょーーっとこいつを走らせても、気付かれない可能性ってこと』

『点検システムの長さは？』

『３０分よ。その間に泳ぎ切らないと、私達の身が危ないわ』

『目的地に一番近い離島で海上から侵入可能なところは……ここか』

海地図を指でなぞりながら難しい顔をするイクス。３０分で泳ぎ切るには少し遠い距離だ。だが、やるしかないだろう。

『ふふ、大丈夫よ』

そんなイクスを安心させるようにレイラが微笑んだ。

『足にフィンをつければ距離はそこまで問題じゃないわ。気をつけなきゃいけないのは――浮上する時だけ』

水深の深いところから浮上する時はゆっくりでなければならない。
人間は深く潜れば潜るほど、全身にかかる水圧が増していく。地上にいる時と異なる環境に身体を慣らすには時間が必要だ。水中の縦移動はゆっくり体を慣らしていきながら進まなければ、命に関わる場合がある。

今回のイクスとレイラの場合、潜る時はのんびりできる。しかし一度エレベーター内部に侵入したら３０分という制限時間がつく事になる。その中で、焦らずに浮上を済ませる事が重要だ。

足にフィンと呼ばれるゴム製の器具をつけて泳ぐと、普通に泳ぐ時よりもスピードが出やすい。だからこそ浮上時は急ぎすぎないように気をつけなければならない。

『焦っちゃダメよ』

暗い整備用トンネルを電灯で照らし出したレイラの目がイクスにそう念押しているように見えた。
深い水の中でイクスは頷き返す。

大丈夫だ、事前に打ち合わせた事はしっかり覚えている。

真っ暗闇の整備用トンネルを抜けると、ようやくエレベーター通路だ。

エレベーターが上り下りするためだけの細長い空間とは言え、五人は同時に並べそうな程の広さがある。イクスとレイラが並んでもなお十分すぎるほどの空きスペースが周囲にあった。
通路内は電子的な光で満たされている。青と赤のブロックが交互にチカチカ点滅して闇をネオンに照らしていた。

イクスは自分の顔にかかる赤い光にギクリと目を細めた。海の中を貫くアラート点灯はあまり心臓に良くない。地の底から響いてくる得体の知れない重金属音と合わせて、やたらむたらに不吉な気配を掻き立てる。
急いで抜けるべきだ。だが、焦らずに。

イクスとレイラはエレベーター通路を照らす赤と青の光をかいくぐるように進んでいった。
定期的に壁に埋め込まれた電子掲示板が光り、『点検中』の文字を踊らせる。きっとエレベーター整備者のために用意されただろう。

あの文字が浮かんでいる間は安心して泳いでいける。

目的の離島へと泳ぎ進んでいると、イクスは手元の水深計が少しずつ数値を増やしていることに気付いた。30、32……どうやらエレベーター通路は下方向への傾斜がついていたらしい。
水深40ｍでようやく計測が止まった。

思っていたよりも深い。ここからゆっくりと登らなければイクス達の身体内部が損傷する可能性があるというのに、見込みよりも随分と深いところまで来てしまった。

エレベーターが動き出すまでの残り時間はあと１０分。余裕はあるはずだ……たぶん。

ダイバーズウォッチを持ってこれなかったから正確な時間が分からないのが痛い。

『イクスくん、焦らない』

レイラがイクスの肩を小突いて、凛々しい視線を向けてきた。落ち着きを払ったレイラの赤い目に救われた気分になって、イクスは小さく頷き返した。

そうだ、イクスが先に焦り始めるわけにはいかない。怖いのは自分へのダメージではなく、レイラが傷つくこと。イクスが万が一に混乱して窮地に陥れば、レイラはきっとイクスを助けにくるだろう。それだけは避けなければならない。

――ゆったりとした浮上が始まった。

レイラとイクスはお互いの利き手を握りしめた。堅いダイビンググローブ越しにレイラの手がぎゅっとイクスを握る。どちらかが急いてしまった時に止められるようにだ。

大丈夫だ、時間に余裕はある、はず。ぐいぐいと上に泳ぎたくなる気持ちを抑えて、レイラと肩を並べて上を目指す。

……ところでリニアの仕組みの話だ。元々リニア技術とはリニアモーターカー――巨大な車両を高速で動かすために使われていた技術だった。『電線の要らない電車』、『浮く電車』として、発明当時はずいぶんと世間を賑わせたらしい。イクスが生まれる数百年も前の話だ。

時を経るにつれて技術は拡大利用され、今では縦横無尽に水中を移動する海中エレベーターにさえもリニア技術は使われている。どれほど高度化し、繊細化しようとも、リニア技術の根本的な仕組みは変わらない。S極とN極、２つの反発し合う磁石を交互に敷き詰めることにより、列車のような大きな物体を動かすための推進力を得る。

だから、実は潜入前から少しだけ嫌な予感はしていた。

もし、潜水中にエレベーター点検が終わってしまったら、今は停止している磁力も動き出すのではないだろうか。そしてエレベーターのような巨大な金属箱を水圧に逆らって引っ張り上げられるほどの、強力な磁石が動き出した時――すぐそばにいたイクスとレイラはどうなってしまうのだろうか？
嫌な予感が更に増したのは、エレベーター通路内の電灯が切り替わりはじめた時だった。『点検中』と表示されていた文字がパッと消えた。

離島の入口はもう少しだ。離島側にある整備用トンネルに入ってしまえばきっと大丈夫。トンネル入口のドアはもう見えているから、その中に泳ぎ込めば良い。

しかし、壁に埋め込まれた電子掲示板に『点検完了』の文字が赤く映り込んだ瞬間だった。

途端にイクスとレイラの体が吹っ飛んだ。

べったりと壁に体が押し付けられてしまう。今まで沈黙していた磁石が働き出したのだ――まだ磁力は弱い。だがエレベーターを駆動させるために徐々に威力を強めているようだった。

ベキリ。

耳の後ろから聞こえた不吉な音の正体がイクスにはすぐ分かった。ボンベだ。金属製のボンベがリニアの磁石に引っ剥がされそうになっている音だった。慌ててマウスピースを捨てると、大量の気泡がイクスを包んで、上へと登っていた。マズい。ボンベが爆発しそうだ。

危機感を覚え始めたイクスよりも一手先に動き始めたのがレイラだ。イクスが背負っているボンベの肩紐がナイフに引きちぎられる。引きちぎる、というよりは、磁石に引っ張られたナイフの先が壁に突き刺さる勢いで肩紐もちぎれた、と言うべきだろうか。

あっという間にイクスは自由になった――しかしレイラはまだ磁石の壁に貼り付けられている。イクスはダメ元でナイフを壁から取り外す。迷っている暇はあまりなかった。踏ん張るところがない水の中で、なんとか身を捻って、磁力の影響をナイフから引き離す。手を離せばすぐにまた壁に向かっていきそうだが、一回斬りつけるくらいならなんとかなりそうだった。

レイラの方の肩紐も同じように切り離した。

――今の動作でどれくらいの時間を使った？いや、そもそもエレベーターは動き出してしまった。もしかして、こっちに向かってきている？

ちらりと見上げた電光掲示板には『異物検出』と赤い文字で書かれていた。やっぱり、あまり良い予感はしない。

エレベーター通路を満たしていた水が突然うごめき出し、津波のようにイクスとレイラをさらった。とっさに伸ばしたイクスの手をレイラが掴む。これではぐれることはないが、このままでは押し流されてしまう。目標である整備用トンネルはもう少し先だ。このまま流されていけば目的地にたどり着くが――流されている途中にドアハンドルを掴まなければいけない。掴みそこねれば水に押し流されて二度と戻ってこれないだろう。この水流がどこに流れ込んでいるのかは分からないが、異物が押し流される先なんて大抵ゴミ箱か何かに決まっている。人間が入る事を想定されていない場所である事だけは確かだ。

チャンスは一回。

イクスは両足につけたフィンを大きく動かして、真上へと手を伸ばした。

エレベーター通路奥から押し寄せてくる水圧の力も借りて、猛スピードで整備用トンネルの入口へと進んでいくイクスとレイラ。移動距離は――クソッ、分からない。１メートルもない距離だったら良いのだが、水中では距離感も狂いやすい。下手したら一気に数メートル近く浮上してしまったかもしれない。

だが、このまま空気ボンベもない状態でどこかへ流される方が危険だった。

イクスはレイラの手を片手に握ったまま、整備用トンネルのハンドルを左手でキャッチする。体だけがグイッと引っ張られて危うく手が滑りかけたが、レイラの手がイクスの手を覆って、押さえつけてくれた。
水圧は、怒涛の水流となってイクスとレイラを吹き上げようとしている。
するとレイラがイクスの腰に抱きついてきた。

『れ、レイラさん！？』

驚いたイクスがそちらを見ると、想像以上に真剣なレイラの目がこちらを見ていた。イクスの体を伝って、整備用トンネルのドアに触れたいようだ。……そうだ、ここの暗証番号を外せるのはレイラだけだ。

器用にイクスの胸の中に収まるレイラ。するりと水流に流されそうになったその体をイクスは慌てて右手で捕まえて押さえつけた。レイラは全身をイクスに任せ、整備用トンネルの解錠作業を始めた。

パネルに触れ、指先でいくつかの数字を叩き込む。わずか２秒の素早い作業だった。整備用トンネルのドアが開く感触がイクスの手に伝わってくる。

イクスは迷わずにハンドルを握る左手を引っ張った。ぽっかりと空いた穴から冷たい海水が流れ込んでいく。外の海水の方が冷たいらしい――そんなぼんやりとした思考に意識を持っていかれそうになったイクスをレイラが整備用トンネルの中に押し込んだ。

レイラとイクス、二人でなだれ込むように狭いトンネルに入る。レイラはすぐにパネルを操作して、開いたばかりの整備用トンネルのドアをロックした。

ゴンッ。

閉まったドアの向こうで衝突音。重々しい質量が何かをぐしゃぐしゃに潰したような音だった。堅い金属出できているはずのドアがひしゃげそうな勢いだった。

安全圏にいる今でも、聞きたくない嫌な音だった。

整備用トンネル内を急いで泳ぐと地上への出口が見えてくる。ドア代わりの鉄格子を開けて、タイルの床の上にびしょ濡れの体を投げ出した。

「……ふぅ。レイラさん、頭痛とかはありませんか？」

「今のとこ大丈夫そう。イクスくんは」

「問題ありません」

無事に侵入成功だ。
レイラとイクスは顔を見合わせて、深く頷きあった。
