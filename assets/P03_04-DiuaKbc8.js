「アイツらはただ、面白がってたんでしょうね。怯えるハンナちゃんも可愛いだなんて言って、楽しんでた。ハンナちゃんがなんでもないことみたいに強がるから、あの子は大丈夫なんて思って。本当は、泣きそうなくらい怖がってたのに……」

　語りながら、ふと自分の手元に視線を落とすドランク。伏せられた瞳に暗い光が宿った。

「だから私が守ってあげてたの」

　ドランクの口からこぼれた呟きは、聞く者をぎくりとさせるようなほのかな狂気を孕んでいた。

「一緒に帰ろうとするとハンナちゃんが怖がるから、こっそり、ハンナちゃんに見つからないように後をつけて。変なオッサンが居たらコテンパンにしてあげたわ。それだけ、私はあの子を心配して――」

「しかし、その心遣いが逆にハンナを追い詰めた」

　冷えたマスターの声色にはっとドランクが顔を上げる。マスターは変わらずに微笑んでいる。しかし瞳の奥から他者を全て突き放すような冷たさが滲みだしていた。

「どういう……こと？」

「ハンナは帰り道、誰かにつけられていることに気付いていました。得体の知れないその何者かにいつか何かされるのではないかとずっと怯えていた。……もっとも、私がそれを知った時にはすでに彼女は店から立ち去っていましたが」

　元々、度を越した常連客たちのアピールに心をすり減らしていたハンナだったが、正体のわからないストーカーに家まで毎日つけまわされてすっかり弱ってしまっていた。接客中は必死で笑顔を取り繕っていたが、ある日急に心がぽっきりと折れてしまったのだろう。ハンナは店に出勤することもできなくなり、そのままMYSTIQUEのバーテンダーも辞めた。

　マスターがそのことを知ったのは全てが終わった後だった。ある日、急に店に来なくなり、連絡も取れなくなったハンナを心配して彼女が住むアパートに向かうとそこはもぬけの殻になっていた。アパートの管理人に託された置手紙を読んで、初めてマスターは人知れず苦しんでいたハンナの心に気付いたのだった。

「そ、そんな……私、そんなつもりじゃ……」

　マスターの話を聞いたドランクが慟哭の声を上げる。ハンナの家を知っていたのは、ドランクが彼女の帰り道をずっとつけていたからだろう。

「そんなつもりでなくとも彼女の心を最後に壊したのはあなたです」

　動揺するドランクを一蹴するように冷たくマスターが言い放つ。しかし何かを思い出したかのようにマスターは表情を変えて、カウンターの上のマテリアルを見た。

「そして………一番近くに居ながら、彼女の心を守れなかったのが僕だ……」

　マスターは悔恨に満ちた呟きをひとりごとのように漏らした。ハンナを失って、誰よりも傷付いたのが彼だったのだろう。打ちのめされた様子のマスターにドランクが慌てて弁明しようとした。

「私、そんなことしてたなんて思ってなかった！悪気はなかったの！ただ、ハンナちゃんが心配で……！！」

「いえ……いいんです」

　ドランクが言いつのろうとするが、マスターが首を振ってそれを押しとどめる。

「もう終わったことですから。過去に起きたことは取り戻せない。もう彼女は居ないのだから。だから、僕は……」

　マスターが優しく微笑んだ。場違いなほどに穏やかな微笑に、イクスは知らずのうちに前に出てドランクを背に庇っていた。

　密やかに狂気が煮詰まり、そのまま腐り落ちたようなおぞましい気配を感じた。

「………ねぇ、マスターさん。聞いてもいい？」

　イクスが感じたものと同じ気配を感じたのだろうか。緊迫感が滲む、凄みのある笑みを浮かべてレイラがマスターに問いかける。

「はい、なんなりと」

　頷くマスターの様子は見た目だけは普段と変わらないように見えた。

「その紙袋なんだけどさ」

　レイラが示したのはカウンターの上に置かれた小さな紙袋だ。先ほどマスターが買い出しにでかけた際に持っていた。改めてその袋を見て、イクスはおかしな点に気付く。買い出しした物を入れるには小さすぎる。

「ねぇ、その袋、買い物するにはちょっと小さいんじゃない？本当はさっき、何しに行ったの？」

　疑念の視線がマスターに集まる。四人に見つめられてもなお、マスターは動じた様子を見せなかった。

「……困りましたね」

　穏やかに言いながら、マスターは紙袋を手に取った。そして手に取った袋を躊躇なくカウンターの上でひっくり返す。たくさんのビー玉を落としたように、バラバラと音を立てて小粒の何かがカウンターの上に広がった。

うっすらと光を放つそれはビー玉ではなく、マテリアルの欠片だ。淡く輝く様はマテリアルとよく似ているが、決定的に違うものがある。イクスは愕然とした思いでそのうちの一つを手に取った。やはり“音”は鳴らなかった。

「これは、あの欠片！？それも、こんなに……」

　カウンターに散らばる欠片はMYSTIQUEの薔薇園で拾ったものと同じものだ。マスターは心当たりがないと言っていたが、彼が落としたものだったのだろう。

「厳密に言えばこれらはマテリアルではありません。劣化品……模造品のような物です」

「模造品……？なんで、そんな物が……いいえ、それより、欠片とは言えどうやってこんなに大量に！？」

　レイラが信じられない物を見るように、カウンターに散らばったマテリアルの欠片を見つめている。マテリアルの素材は人間だ。これほど大量の人間がマテリアルに変えられたとでも言うのだろうか。何か冷たいものがイクスの背中を駆け上がった。

「ですから模造品ですよ。簡単に作れる代わりに質は悪い。これらに本物のマテリアルのように複雑で美しい“音”を奏でることはできません」

そう言って、マスターがカウンターの上に置かれたダイヤのマテリアルに目を向けた。マテリアルの欠片に埋もれながらも一等強い輝きを放つそれを、まるで愛しい者を見るような優しい視線で見つめた。

「彼女のマテリアルほど、美しい“音”は奏でられない……」

「あなた、“音”が鳴るのは聞いたことがないって言ってなかったっけ。嘘つきさんだったのね」

「“音”のことを知っていると思われると、不都合だったもので。まさか、あなたがたがここまで来るとは思いませんでしたが」

　ふと、カチッ、と小さな機械音が聞こえた。やけに大きく響いたその音の方を見れば、時計がちょうど12時を指している。真夜中12時。昨日、ビリーと連絡が取れなかったのも同じ時間だった。

　図ったように、美しくも不吉な“音”が流れ始めた。ビリーとの通話で聞いたあの甘美な“音”だ。心に染み込む暗い影、とろけるほどに甘い美酒を脳髄に直接流し込んでくるかのようなおぞましさがそこにはあった。
カウンターの上のダイヤのマテリアルの放つ光が妖しいものに変わっていた。マスターに感じたものと同じような、密やかな狂気を感じてイクスはぞっとする。

「な、何これ……？何この音……！？音が……同じ音なのに、違う音がたくさん並んで……一つの音になったみたい……まるで生き物みたいに……」

　急に流れ始めたマテリアルの旋律にドランクは狼狽えた。自分の耳が信じられないとばかりに両耳を押さえてうずくまる。

「とても綺麗なのに………聞いていると、震えが止まらない……これが、あなたたちの言ってた“マテリアル”なの……！？」

「本当はこのマテリアルはハンナの物だったんです」

　怯えるドランクを無視して、静かにマスターは語り始める。その視線はダイヤのマテリアルから離れない。

「これを手に入れた時はただの珍しい宝石だと思っていましたから。この宝石を渡して、ハンナにプロポーズをしようと思っていたんです」

　マスターはネックレスの形をしたダイヤのマテリアルを婚約の話としてハンナに贈ろうとしていたが、その前にハンナは失踪してしまった。マスター自身が持っていても使い道がなく、見る度に心が痛んだため、何度も処分をしようと考えたと言う。しかし、結局マスターはそのマテリアルを捨てることはできなかった。その結果、渡す相手を失ったマテリアルは長い間クローゼットの奥にずっと封じられていた。

