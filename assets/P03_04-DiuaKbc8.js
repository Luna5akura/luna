ハンナは店内のインテリアや仕入れについてマスターの相談に乗ることもあり、雇われているというよりはマスターと共に力を合わせて店を経営しているように見えた。まるで新婚の夫婦のようだとドランク自身がハンナとマスターをからかったこともある。からかわれてあたふたと顔を赤くするハンナをドランクも微笑ましく見ていたはずだった。

「最初はちょっと可愛いって思ってただけなのよ。元気で、明るくて、頑張り屋で。いい子だなって思ったの。だけど……ハンナちゃんを構ってるうちに、いつの間にか独り占めしたくなった。そう感じたのは私だけじゃなかったみたいだけどね」

