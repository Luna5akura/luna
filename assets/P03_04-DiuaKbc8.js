　窓から覗くとちょうど二人分の人影が見えた。マスターとドランクだ。二人はカウンターを挟んで向き合うように立っていて、ドランクがマテリアルを片手にマスターに何事かを迫っているように見えた。何やらもめているようだ。

　声は聞こえないが、ドランクは鬼気迫る表情で何かをまくし立てており、それとは対照的にマスターの方は静かに黙り込んでいる。

　店のドアを押すとあっさりと開く。休業の札はかけたが、鍵はかけていなかったらしい。

　イクスたちが店内に踏み入ると、ドランクが振り返って驚いた表情に変わった。

「あなたたち？さっき帰ったと思ったけど、どうしてここに？」

「それは……」

　問いかけられて言葉に詰まるイクス。もしドランクが昨日ビリーを害したのだとしたら、直球に切り出したところで正直に話してはくれないだろう。

　どうしようかとたじろいでいると、レイラがさっとイクスの横から進み出た。

「ちょっと忘れ物をしたのよ。そしたら、何かもめてるみたいじゃない？なんの話をしてたの？」

「……別に、あなたたちは関係のない話よ。忘れ物を取ったら早く帰りなさいな」

　あからさまにイクスたちを追い払おうとするドランク。しかし言われて素直に引くレイラではない。追い払われていることに気付いてすらいないように悠然と腕を組み、レイラは今度はマスターに問いかけた。

「急に店じまいしてたからびっくりしちゃった。何かあったの？」

　マスターは手持ち無沙汰にグラスを磨いていた。グラスを磨き終わり、おもむろに背後の木棚に向かうマスター。マスターの手がすでに並んでいた空きグラスの隣にそっと磨き終わったグラスを置いた。

「……ドランクさんが、個人的な相談があると仰ったので。長い話になりそうでしたので、今日は店を閉めさせていただきました」

　マスターは振り返り、イクスたちにいつもと変わらない微笑みを浮かべる。しかし、変わらないはずのその微笑みに何かぞっとするものをイクスは感じた。

　ドランクは普段と異なるマスターの様子に気付かない様子でいら立ったようにバーカウンターに詰め寄った。

「別に店は閉めないでもよかったのよ。私はただ、ハンナちゃんの居場所が知りたいって言っただけで……」

「ですから、それをお教えすることはできません」

「なんでよ！！」

　ドランクがさっと表情を怒りに染めた。

「教えてくれたらこれ、返してあげるって言ってるじゃない！この宝石、ヤスちゃんの大切な物なんでしょ！本当はビーちゃんにも渡したくなかったんでしょう？別に、居場所を知ったからって言ってハンナちゃんに変なことはしないわ！私はただ、あの子が無事かどうか知りたいだけ！！」

　これ、と言いながらマテリアルをカウンターに叩きつけるドランク。乱暴な仕草に驚いてイクスが小さく肩を揺らす。慌ててマテリアルは傷付いていないかと見るが、ダイヤ型の宝石は騒ぎなど素知らぬ顔で美しく光っていた。

「急に辞めちゃったから心配なのよ。それくらいはいいでしょ。私があの子のことを心配しちゃダメ？私にはその資格もないって言うの！？」

　話しているうちに感情が高ぶったのだろう。ドランクはその場にイクスたちが居るのも忘れてマスターの胸ぐらを掴みかかった。今にも殴りかかりそうな様子にイクスが慌ててドランクの腕を引く。

「ドランクさん！何があったかわかりませんけど、落ち着いてください！」

「…………」

　他人の視線があることに気付いてドランクが怒気をやわらげた。しかし瞳には剣呑な光を浮かべたままだ。
　鋭い視線でマスターを睨みつけるドランク。そんなドランクにマスターはただ沈黙を持って返した。誰も何も喋らない、重々しい空気が店内を流れる。

　沈黙を破ったのはエレノアナだった。

「あの……ドランクさんはハンナさんとどんな関係だったんですか？」

　おずおずと、しかしはっきりとした声でドランクに問いかける。問いかけられたドランクはマスターを睨みつけるのをやめて、エレノアナを静かに見据えた。

「……なんでそんなことが気になるのかしら」

「さっき話してた時に、ドランクさんがハンナさんの家を知っているのが気になったんです。それで……もしかして、仲が良かったのかなって」

「それは………」

　ドランクが気まずげに目を伏せた。深呼吸をしようとして途中で失敗したかのように、口を中途半端に開き、唇を戦慄かせながら短く息を吐いた。嘆息に諦めのような色が宿る。

「…………ただの客と店員よ」

「でも」

「それ以上には私はなれなかった。ハンナちゃんは私を選ばなかったから」

　私は好きだったのに。

　深い罪を悔いるようにドランクは喉から言葉を絞り出した。

「あの子は結局、ヤスちゃんを選んだんでしょう……。知ってたわよ、あなたたちが特別同士だったってことは最初から………」

　マスターをなじるように力なく呟くドランク。それからこらえていたものが抑えきれなかったかのようにぽつぽつとハンナという女性のことを話し始めた。

