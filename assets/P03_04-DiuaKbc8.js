心の奥底ではこれでようやく踏ん切りがつくかもしれない、という期待もあった。マテリアルを手放せなかったのはどこかで彼女の帰りを期待していたからだったが、長い後悔の中マスターは疲れてしまっていた。自分を責め続けることを止められない自分を変えなければ、店を続けることすらままならなかった。

