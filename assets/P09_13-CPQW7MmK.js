ハードな一日だったわね、と言いながらレイラがソファに自分の体を沈み込ませた。

不思議な水流にセレスティア島の浜辺まで流されたレイラ、イクス、エレノアナの三人は宿泊するホテルに戻ってきていた。

疲れ切った、というよりは運動後の清々しさをまとわせながらグッと伸びをするレイラ。ずぶ濡れだった身体はすっかり乾いて、朝方の寒さを振り払うために長袖のパーカーに着替えている。
まだ暗い空の早朝だ。もう少しすればセレスティア島のサファイアの海にきらめく夏の太陽が昇ってくるだろう。

「お疲れ様です、レイラさん！どうぞ、コーヒーです」

挽きたてのコーヒーをエレノアナがテーブルに並べた。３人分のマグが仲良く、あたたかそうな湯気を立てる。
暖気に誘われたのか、部屋を落ち着きなく飛び回っていた小鳥のハピネスが近くに降り立ち、すぐに丸まって眠り始めた。どうやら眠くて、寒かったらしい。

自由なヤツね、とレイラがくすくす笑いながらハピネスをつつく。

「ありがと！エレノアナちゃんもお疲れ様。イクスくんもね！」

「結果的には何事もなかった……って感じですかね……？全員が無事だったのはなによりですけど」

「そうねぇ……マテリアルを解放しても誰も出てこなかったのはちょっと腑に落ちないけど……やっぱり特殊なマテリアルだったって事かしら……」

マテリアルは人間を素材にして作られる。レイラが開発したキュアを使えば、素材にされた人間を元の姿に戻せるのだが……『人魚姫の涙』からは誰も出てこずに、大量の水だけが溢れ出した。
レイラが、ううん、と悩みながら唸る。マテリアル研究者として引っ掛かりを覚えているらしい。
マテリアル研究者と言えば、とエレノアナはもう一人の研究者の事を思い出した。

「そういえばシキさんはどこに行ったんでしょう？」

「あれ……浜辺に流れ着いた時には居たんだが。いつの間にか居なくなっていたな……」

「気まぐれよねぇ。研究者同士、積もる話もあったんだけど……また逃げられちゃった」

「あはは……」

実はシキとメッセージアプリで毎日のようにやり取りをしています、とはまだ言い出せずに、エレノアナは曖昧に笑った。シキはどうにも、レイラとイクスとあまり顔を合わせたくないらしいのだ。秘密の共同研究の事もあるし、まだまだ二人には詳しい事は話せない。

――だけどいつか、ちゃんと話せる日がくるはず。

その時までこの小さな秘密は胸にしまっておこう。打ち明けた時には二人がびっくりしながらも笑ってくれると良いな、とエレノアナは未来の期待に表情を輝かせた。

「あら、エレノアナちゃんったらなんだかごきげんね？」

目ざといレイラがすぐにエレノアナの様子に気付く。

「はい！シキさんとレイラさんが仲良くお話する日が来るかも、って考えていました！」

「仲良くねぇ……そうね、まあ、敵じゃないならそういう日も来るかもしれないわね」

レイラは神妙な顔つきでしばらく考え込んでから、やがて何かに根負けしたように穏やかに苦笑した。


三人がだらだらと穏やかな時間を過ごしていると、軽いドアノックとともに一枚のメッセージカードが部屋に届いた。どうやらシケロンがホテルに届けさせたものらしい。

どうやらイクス宛らしいと聞いて、送られた本人が一番驚いた。

「俺に……？」

恐る恐るメッセージカードを開いたところで、イクスはぴしりと固まった。

『店はそろそろ引退しようと考えている。跡継ぎには君の名を指名しておいた』

「なんでだ！？」

困惑した様子でイクスが何度もメッセージカードを裏返したり、振ってみたりするが、書いてある言葉はそれだけだった。

シケロンらしい、ぶっきらぼうで、口数の少ないメッセージだ。エレノアナはすっかり親しみの湧いたシケロンの厳しい顔を思い出して、ふふ、と小さく笑う。
困りきったイクスを見るレイラもにやぁ、とチェシャ猫のように悪戯な笑みを浮かべた。

「あら、いいじゃない、宝石店！貰っとけば～？」

「そ、そんな気軽に言われても……な、なんで俺なんだ……？」

「はい！イクスさんがシケロンさんを助けたからだと思います！」

「そんなはずは……俺が見つけた時にはもうほとんど浜辺の近くに来ていたし……」

「それでも命の恩人には変わりないじゃない？」

そうだろうか、とイクスが唸りながら首をひねる。

くすくすと笑っていたエレノアナは不意に口元を少し引き結んで、部屋の窓の外へと視線を向けた。焼け付くような熱気を感じたのだ。外を見てみれば、いつの間にか太陽が昇ってきている。透き通るような青い海に、強烈な太陽の光がギラギラと照りつけはじめていた。あまりにも眩い光が地平線を真っ白に染めている。
その眩しさが何故かエレノアナを寂しい気持ちにさせた。

――そっか、シケロンさんはお店をやめちゃうんだ。

胸の中でそう呟けば、哀愁のような何かがうずまき始める。こじんまりとしていながらも豪奢なシケロンの宝石店を思い出してしまった。あんなに『人魚姫の涙』を欲しがって、人魚姫を探していたのに諦めてしまったのだろうか。この場にシケロンが居れば、エレノアナはきっと『どうして』と聞いていただろう。あの無口な宝石商が答えてくれるとは限らないけれど。それでも、尋ねてみなければ答えを手に入れられるかどうかも分からない。

人魚姫が渡してくれた一本の水の花をエレノアナは思い返す。あの花が贈られるべき相手は本当に自分だったのだろうか。溶けてなくなってしまったあの花の形を確かめることすらもう出来ない。
ただただ、あの美しい花を貰った時の優しい気持ちだけが胸に残っている。

「私は、誰かのために何か出来てるかな……」

思わずそんな独り言がエレノアナの口からこぼれ落ちた。

「エレノアナ？」

イクスに声をかけられて、はっと振り向く。振り向いた先ではレイラとイクスがまるで双子のようにそっくりな驚き顔を浮かべていた。二人がどうしてそんな顔をしているのか分からないのと、息がピッタリ合っているかのような表情のシンクロ具合にエレノアナは嬉しいような、むず痒いような気持ちを覚えた。
自然といつもの笑顔が口元に浮かんでくる。

「もっともっと強くなきゃ、って決意したところです！」

「エレノアナに今以上に強くなられたら、そろそろ俺のやる事がなくなってきちゃうんだが……」

「そうそう！エレノアナちゃんにはただでさえ強力な武器があるのに！」

「武器……ですか？」

心当たりがなくて目を瞬かせるエレノアナ。

レイラがにんまりと笑う。こういうときのレイラは大抵、みんなをびっくりさせるようなことを言い出す。なんだろう、とエレノアナの胸が期待に弾む。

いつもはレイラこの笑みでぎくりとするイクスが、まったく気付かない様子でうんうん、と真剣そうに頷いている。その様子を横目で見たレイラがさらににやりと笑みを深めた。

「エレノアナちゃんのコーヒーがないと目が覚めてこないんだから！」

「そのとおりです」

「生きてけないかもしれない！」

「うんうん」

「つまりエレノアナちゃんが居ないと生きていけないのよ――イクスくんが」

「俺ですか！？」

イクスの驚く声にかぶせて、エレノアナの喉からも悲鳴のような困惑した声がひねり出される。なんだかとんでもない事を言われた気がして、顔がかぁっと熱くなるのを感じた。

「「レイラさん！！」」

イクスとエレノアナの抗議の声がぴたりと重なる。

悪戯が成功した子どものようにレイラがケタケタと笑った。こういうときのレイラの顔は少し意地悪だ――だけど、大人の女性らしい美貌があどけない可愛らしさを宿している。ただでさえ華やかな顔立ちがパッと明るく輝いているようで、意地悪なのに、全然憎めない。

「あら、違うの？」

レイラが楽しそうにイクスにたたみかける。

「うっ……違いませんけど……」

「イクスくんが飲めるブラックコーヒーを作れるのはエレノアナちゃんだけだものね～！」

イクスがぐっ、と唸って黙り込んだ。何も言い返せなくなったらしい。

「えっと、じゃあ……」

撃沈してしまったイクスの敵を今日こそ自分が取るのだ。
エレノアナは両手でぐっと握りこぶしを作って、必死に返す言葉を考えた。言い返すなら、ええと、ええっと……そうだ。

「レイラさんの好きな濃いめのエスプレッソを作れるのも……私だけですか？」

「あら」

レイラの目が驚きにきらめく。やった、とエレノアナは笑顔を浮かべた。ちょっとだけ驚きのお返しができた。
三人で旅をはじめてからずっと、目覚めのコーヒーを淹れてきたのはエレノアナなのだ。二人の舌の好みはすっかり把握している。レイラはびっくりする程に濃いコーヒーが好きなのだ――すっきりとした飲み口を好むイクスが間違えて飲んでしまうと涙目でむせてしまうくらいに濃厚だ。二人の正反対な好みぴったりの二杯を同時に淹れられるのは間違いなくエレノアナだけである。

パチン、と瞬きをしたレイラが弾けるような笑顔を浮かべた。

「ふふ、もちろん、それがないとすーーーっごく困るに決まってるでしょ！！エレノアナちゃんのエスプレッソ以外じゃ全然頭が冴えないんだから！！」

ゲラゲラとひとしきり笑ってから、レイラは、ねえ、と元気よくソファから立ち上がった。

「どうせならもうちょっと遊んでいきましょうよ！」

「わあ、良いですね！今ならまだ朝早いので、人も少ないかもです！」

楽しそうな提案にエレノアナの目も輝く。今まで調査ばかりしていたから、泳ぎ足りないとはこっそり思っていたのだ。こんなに綺麗な海に来ているのだから、どうせなら疲れてくたくたになるくらい夢中で遊びたい。

「二人とも元気すぎないか……？」

戸惑うイクスの左腕をレイラがむんずと掴んだ。

「エレノアナちゃん、イクスくんを引っ張って！泳ぎにまだ苦手意識がありそうなイクスくんに特別水中訓練するわよ！！」

「苦手って、いつの話をしてるんですか！？」

内陸育ちのイクスは子供時代に湖や海で泳いだ経験がなかった。小さい頃に触れた事がなかったからなのか、レイラとエレノアナに出会ったときはまだ水が少し苦手だった。だがそれはずいぶんと前の話で、湖畔育ちのエレノアナと泳ぎが得意なレイラに連れ回されているうちにとっくに克服済みだ。

でも、別に、その時から泳げなかったわけじゃ……とブツブツ呟くイクスをレイラが引きずっていく。置いていかれないようにとエレノアナもイクスの右腕を掴んだ。引っ張る力が二人分になって、いよいよイクスが弱りきった様子になった。

「そもそも昨日からほとんど泳ぎ通しですよ！？まだ泳ぐんですか！？」

「だって昨日はダイビングだったじゃない。エレノアナちゃんも居なかったし。ねー？」

「ねー！」

「ちょっ……ハピネス！寝てないでエレノアナだけでも止めてくれ！」

名前を呼ばれて、眠っていた青い小鳥が迷惑そうに顔をあげる。引きずられていくイクスを見つけてしばらく眺めていたが、呑気なあくびをこぼして再び眠りに戻った。

「ハピネス！！」


「私たちの夏はまだまだ終わらないわよーー！」

「はい！」

三人くっついて団子のように部屋のドアをくぐりぬけ、朝日が眩しいビーチへと向かう。
セレスティア島に照りつける夏はまだ始まったばかりだった。
