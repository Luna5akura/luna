ティアのマテリアルが暴走してから数日が経った。ティアは無事に人間の姿に戻り、ティアのマテリアルに取り込まれていたゲノムの施設も共に解放された。攫われてマテリアルにされた人々も人間の姿に戻っており、今は一時的にロードの屋敷で保護されている。身元がわかり次第、家族の元に帰していく予定らしい。

既に売られてしまったマテリアルの行方はタヌタを中心にして、ロードの屋敷の者たちが探している。ゲノム社の社員たちは自警団に捕らえられた一部以外、気付けば行方を眩ませていた。ティアの父親であるゲイスもそのうちの一人だ。二度と街には近づいてこないだろうが、もし今度顔を合わせたら捕まえてやる、と意気込んでいたのはティアだ。ティアはマテリアルになってしまった他の人格を探しつつ、タヌタたちの手伝いをすることに決めたらしい。今はロードの屋敷にひとまず身を寄せている。

そのティアに迎えられて、イクスたちはロードの屋敷を訪れていた。ロードの葬式に呼ばれたのだ。葬式には多くの人々が参列し、屋敷裏の墓前に無数の花が捧げられた。幼いながらも喪主を取り仕切るタヌタの周りはひっきりなしに挨拶にくる人々が訪れ、ロードの交友関係の広さが垣間見えた。

一言だけ挨拶して帰ろうとしたイクスたちを引き留めたのはティアと屋敷の使用人たちだ。タヌタが話したいと言っていたから、人の流れが落ち着くまで待っていてほしいとのことだった。

タヌタが来るまでの時間を潰すためにイクスたちはロードが良く釣りをしていた湖に向かっていた。

「ええええっ！？エレナとノアナってエレノアナなの！？」

ティアが驚愕の声をあげた。そんなティアを見て、イクスも驚く。

「気付いてなかったのか！？」

「誰だろうってずっと思ってた……えー！？マテリアルになった時に合体しちゃったの？」

「いや、逆だよ。元々エレノアナ一人だったのが、マテリアルにされかけた時に二人にわかれたんだ」

「ええ……そんなことあるんだ、びっくり……」

「だから多重人格くらい、気にしなくて大丈夫ですよ、ティアちゃん！」

「う、うん……なんか説得力あるね……」

エレノアナの笑顔の勢いに押されるようにティアは頷いた。

ティアの心の中から戻ると、イクスはエレノアナの笑顔に出迎えられた。エレノアナはちゃんと、エレノアナのままだった。しかしエレナとノアナとしてティアの心の中に潜った記憶もしっかりと残っているらしい。

「それで、ティアちゃんはタヌタくんと仲直りできたんですか？」

エレノアナがティアに問いかけると、ティアはふにゃりと顔を笑みの形に崩れさせた。それだけで答えがわかるというものだ。見ているイクスたちの口元にも笑みが浮かぶ。

「うん……！ごめんね、って言ったら気にしてないよ、って。そしたらね、タヌタがね、お友達になろうって……ティア、はじめてお友達ができちゃった……」

「よかったな」

「うん！イクスお兄ちゃんありがとう！エレノアナお姉ちゃん、レイラお姉ちゃんも！」

「あら、私は何もしてないけど？」

名を呼ばれて、意外そうにレイラが目を瞬かせた。

「ティアを止めてくれたのはレイラお姉ちゃんでしょ？あの“音”、すっごい綺麗だった！！」

「そう言ってくれると嬉しいわね」

「レイラさん、そう言えば……」

イクスはレイラをこっそりと呼び寄せた。エレノアナとティアから少し離れて、小声で尋ねる。

「あれって、前に言っていたマテリアルプロトですよね、レイラさんのお父さんが作ったって言う……壊れちゃったけど、よかったんですか？」

「いいのよ。使える物をずっと取っといてもしょうがないし。あそこで使うのがベストだったと思うわ」

「でも……」

マテリアルプロトはレイラの母親の形見のようなものだったはずだ。ティアを止めるために必要だったのは事実だが、形見を壊してしまう形になってしまった。明るく振舞うレイラが本当に気にしていないのか、探るように見るイクス。

「いーの、いーの！形見なんかなくたって、私はパパとママの娘なんだから。……良くも悪くもね」

レイラは何かを追憶するように目を伏せた。胸の奥で何かが痛んでいるような横顔だったが、不思議と陰りはない。

「パパがマテリアルを作っちゃったって言う事実はずっとついて回るんだと思う。それが、私とパパとママの繋がり、みたいなもので、形見とかなくても、そっからは逃げらんない気がしてさ。逃げる気もないけどね。私はマテリアルにされた人を助けに行ってもいいし、行かなくてもいい。でも……」

「レイラさんの父が関わっていようと、関わっていなかろうと、マテリアルにされた人を放っておけるレイラさんじゃあないですもんね」

「そういうこと！」

「あいたた……」

レイラに背中を叩かれて、よろめくイクス。何かが吹っ切れたようなレイラの明るい態度に苦笑する。障害も困難も丸ごと跳ねのけていくこの強引な前向きさこそレイラらしい。本当に形見のことは引きずっていないようだ。

「……何もしなくてもいいの？」

少し先を歩いていたティアが振り向いて、迷子の子どものような目でレイラを見つめた。話を聞いていたらしい。同じく振り向いたエレノアナは楽しそうにしている。レイラの母親の形見の話までは聞こえなかったようだ。

「ティアのパパは悪いことをたくさんしてるよ。だから、ティアは、ティアが止めなきゃって思って……」

「止めてもいいけど、絶対にティアが止めなきゃいけないって訳でもないと私は思うわ。だって、人生に“絶対”なんて、本当はないもの」

「“絶対”なんてない……」

「これをやっときゃ正解、みたいなのはないってこと！自分のやりたいことくらい、自分で決めないとね」

「ティアのやりたいことかぁ……」

ティアは悩む様子を見せた。

「うーん……もっと、強くなりたい、かな。……パパが怖くなくなるくらいには強くなりたい」

「龍になった時のティアはすごい強かったけど……」

「あれはマテリアルになってたからだもん！あれは違うの！」

イクスの言葉に頬を膨らませるティア。だが、ティアは街全体を呪うほど、強力な“音”を奏でるマテリアルになるような少女だ。まだ幼いところはあるが、弱い心を持っているとは考えにくい。

イクスの考えを余所に、ティアは不安そうに呟く。

「……ティアは弱いティアから変われるかなぁ」

「変えたいと思ったなら、変えられるわ。もうその一歩をティアは踏み出しているでしょ？」

「そっか……うん。今までのティアじゃないティアになりたい。変わりたいよ」

「それでよろしい！」

レイラの自信に満ち溢れた笑みにつられて、ティアも嬉しそうに笑顔を浮かべる。あどけない少女らしい、無邪気な笑みだった。


イクスたちが湖に辿り着いてしばらくすると、タヌタが大きく手を振りながら駆けてきた。

「イクスさーーーん！エレノアナさん！！レイラさん！！！」

息を切らせてイクスたちの前まで走ってくるタヌタ。急いできたのか、額にうっすら汗が浮いている。

「ごめんなさい！中々抜け出せなくてお待たせしてしまいました！」

「すごい人でしたね！」

エレノアナの言葉を聞いてタヌタは苦笑した。

「ボクもびっくりしました……おじい様は色んな人とお友達だったみたいで。おじい様のこと、あんまり知らなかったんだなぁって」

ロードはジェノサイド社とマテリアルの取引ができるような立場の人間だったのだ。晩年になって人を遠ざけていたが、元々知り合いは多いだろう。それを一人で引き継ぐことになったタヌタにはこれから様々な思惑を持った人間が寄ってくるかもしれない。

「大変だな……」

「大丈夫です、イクスさん！お屋敷のみんなも居ますし！」

「ねえ、タヌタ。そう言えばタヌタのパパは来たの？」

ティアが尋ねると、ちょっとだけ残念そうな顔でタヌタは首を振った。

「ううん。お父様は来なかったよ。そうじゃないかなって思ってたけど……」

「きっと………なんか理由があったんだよ」

尋ねたティアの方が悲しそうな顔をしているのを見て、タヌタが仕方なさそうに口元を緩める。

「うん……ありがとうティア」

「タヌタに会いたくなかったわけじゃないと思うから！そこは勘違いしないよーに！！」

腰に手を当てて、強く主張するティアにタヌタはようやく満面の笑顔を浮かべた。

「そうだね。ティアが言うなら、そんな気がしてきた！」

「ま、傍に居ない方が良いことってありますよねぇ」

「え？」

ふとティアの声色が変わり、タヌタが驚きの声をあげる。曖昧な笑みを浮かべたかと思うと、ティアはすぐに無邪気な笑い声をあげた。

「……って、二番目のティアが言った！」

「なんだぁ、びっくりした！また別のティアが話してたのかぁ」

「えへへ、最近よく茶々入れてくるんだよねー！特に二番目がすっごいうるさいの！手を洗え―、とか！ドレスの裾が乱れてるーとか！五番目も見てるだけで止めてくれないし！」

「ティア、ややこしいからみんなに名前つけようよ……誰が誰だかボクよくわかんない……」

「名前かぁ。考えてみる！」

「すっかり仲良しね」

レイラが面白いものを見るような目でタヌタとティアを眺めていた。タヌタもティアの心に住む複数の人格を受け止めているように見えた。二人で話に夢中になっていたことに気付いたタヌタとティアが揃って照れたような顔をするのが微笑ましい。

ぺこりとタヌタがイクスたちに頭を下げた。それを見て、ティアも一緒に頭を下げる。

「改めて、ありがとうございました！！おじい様のことも、街のことも。それに……ティアのことも」

「あ、ありがとうございました！！」

「俺たちは、俺たちのしたいことをしただけだよ」

大したことをした覚えはなかった。だが、誰かの役に立てたという事実がイクスの胸にじんわりと広がる。思ったままの言葉を口にすると、レイラがニヤリと笑った。

「うちのイクスくんはキザねー」

「レイラさん！？」

「そういうところもかっこいいですよね！」

「エレノアナまで！？」

エレノアナにまで否定されず、なんだか裏切られたような衝撃をイクスは受けた。慌てて仲間二人を見比べるイクスを見て、レイラとエレノアナが楽しそうに笑う。

「勘弁してくれ……二人にからかわれたら敵わないよ……」

「からかってるつもりじゃないんだけど、ねー？エレノアナちゃん！」

「ねー、レイラさん！」

「いいなー！イクスさんたち仲良しだ！！」

「ボクたちも仲良し……だよ？」

「…………え？」

「え、ええ！？仲良し、じゃない……？」

タヌタの発言にティアが不思議そうな顔をした。それを見て、タヌタがショックを受けたようによろめく。涙を目に浮かべてふるふるしているタヌタに今度はティアが慌てた。

「な、仲良し！！仲良しだよ！！！タヌタがいいなら、ティアも仲良しがいい！」

「よ、よかったぁ……嫌われちゃったかなって思った……」

「嫌いになんてならないよ！！むしろ、そのティアみたいなのと……」

ごにょごにょと呟くティア。言葉にならない何かを吐き出した後、ううん、と気持ちを切り替えるように首を振った。

「そうじゃないね。ティアは、タヌタのお手伝いするって決めたから。だから、えっと、これからもよろしくお願いします！」

「こ、こちらこそお願いします！！」

ぎこちなくお辞儀をしあう二人を見てイクスたちも穏やかな気持ちになった。

それからいくつか言葉を交わして、イクスたちは出立することにした。わかれの挨拶をして、帰り路につく。
山の向こうに太陽が沈みゆき、木々や木陰を赤く染めていた。ふと、強い追い風が吹き、イクスたちの髪や服を乱す。

「バイバイ、イクスさん、エレノアナさん、レイラさん。――バイバイ、パパ……」

風に乗ってティアの声が聞こえたような気がしてイクスは振り返る。離れたところでタヌタとティアが笑顔で手を振っていた。もうティアは大丈夫だろう。二人の笑顔が眩しくてイクスは目を細める。

イクスも軽く手を振り返し、レイラとエレノアナと並んで二人に背を向けて歩き出した。


