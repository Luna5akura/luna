　イクスの頬を一筋の涙が流れ落ちた。
　じん、と頬に涙が染みる。どうやら顔を擦りむいたようだ。
　ふと自分の手を見てみると、随分と小さい。腕に浅い擦り傷がついていて、既視感のようなものに襲われる。改めて辺りを見回してみると、電波塔のてっぺんに立っていることに気付いた。
　朧気な記憶で理解する。これは、ずっと昔にあった、本当の出来事だ。まだ就学前だったイクスがビリーとこっそり電波塔を訪れて、遊んでいたときの記憶。男同士で意地の張り合いになって、誰が鉄塔のてっぺんまで登れるか競争をしたのだ。あまりの高さにビリーは中ほどで脱落してしまい、イクスだけが登り続けた。
