起動した端末の明かりは見えているものの、機械のおかげでイクスたちの居るところは入口からは死角だ。幸いと、ゲイスにはまだ見つかっていない。気絶させたスーツの男も、この暗がりならしばらくは見つからなさそうだ。

――どうする？

レイラの目に問いかけられ、イクスは素早く周囲を見回した。すぐそばに、しばらく使われていなさそうな執務机があった。二人で潜り込んでも余裕がありそうな広さの机だ。

イクスが目線でそちらを示すと、レイラも応じて頷き返す。二人は音を立てないようにゆっくりと、身をかがめながら移動して机の下に潜んだ。そこからゲイスたちの様子を窺う。

「まあいいか。おい、お前らとっととやれ」

しかし、指示と共に運ばれてきた少女を見て二人は嫌な予感を覚えた。

何故気付かなかったのだろうか。タヌタが攫われてマテリアルにされたのならば、他の行方不明者の末路も同じマテリアルであることに。

マテリアル化の機械が稼働をはじめ、黒服の男たちが機械の中央へと少女を引きずっていく。マテリアルにしようとしているのだ。少女は弱っているのか、ぐったりと引きずられるままだ。

隣でギリッ、とレイラが歯を食いしばる音が聞こえた。今にも飛び出していきそうな鬼気迫る顔に、無言でイクスはレイラの手を掴んだ。

「止めないで、イクスくん」

掴まれた手を見もせずに冷たく言い放つレイラ。

「無理です」

だからこそ、イクスもあえて冷たく返した。

「あの子たちを見捨てろって言うの！？今、人間が道具にされようとしてるのよ……！！」

イクスも同罪であるとばかりにレイラが強い眼差しで睨む。ゲイスたちに聞こえないように抑えた声から暴れだしそうなほどの怒りを感じた。だからこそ、イクスは強くレイラを制する。

「無理です、レイラさん。…………無理なんです」

イクスはそう言って、唇を噛み締めた。

目の前で人間がマテリアルになるところなど見たくはない。だが救う手だてがないのだ。何度もイクスは部屋にいる男たちを倒す方法を考えたが、何も思い浮かばなかった。

「ここで失敗して、俺たちが捕まったら…………タヌタのことをロードさんに伝えられない」

「――――――っ！！」

「大丈夫です。キュアがあれば…………後であの子たちも元に戻せる」

レイラの顔が悔しそうに歪んだ。イクスも同じ気持ちだった。何も考えずに飛び出せたら良かった。こんな時に冷静に考えてしまう自分がイクスは悔しくなる。

部屋に青白い光が走り、少女の悲鳴があがった。光が収まると少女の姿はどこにもない。ゲイスが小さな石を拾い上げるのが見えた。マテリアルに変えられてしまったのだ。

「ちっちぇ。クズ石だ。クズからはクズしか採れねぇなぁ」

聞くに堪えない言葉がゲイスの口から吐かれた。それでもイクスたちはそれを見ていることしかできない。
これほどまでに自分は無力だっただろうか。噛み締めたイクスの唇から血が流れたが、ちっとも痛くなかった。

隣室で捕らえられていた人たちが全員マテリアルに変えられ、ゲイスたちはどこかにマテリアルを運びに行った。クズだらけだと笑うゲイスが立ち去り、静かになった部屋でイクスとレイラは机から這い出る。

「……レイラさん、行きましょう」

「……………………ええ」

レイラはイクスと目を合わせずに頷いた。機嫌を損ねてしまったらしい。それだけのことをイクスはレイラに強いた。仕方がないと先に歩きだしたイクスの肩をレイラがぐいっと引き留める。

振り向くと、怒りを消したレイラが弱々しい表情でイクスを見上げていた。

「ごめん、今、大人げなかった。……止めてくれてありがと、イクスくん」

「……いえ」

イクスは何故か泣きたいような気分になって、弱々しく笑った。
