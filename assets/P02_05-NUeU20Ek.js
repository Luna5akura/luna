ほんの少し身じろぎをした、その程度の軽い動作で黒龍が身をひねる。すると、長い尾が鞭のようにしなり、二台のヘリコプターを鋭く打ちつけた。取り囲んでいた電気檻を尾が通過したが、当たったことに気付いた素振りすらない。

尾に打ち付けられた機体はへし曲がり、墜落していく。落下したヘリコプターからの電流が止まり、黒龍を捕らえるための檻は呆気なく瓦解した。

不利を悟ったのだろうか。ゲノム社のヘリコプターは一度引こうとするが、黒龍の動きの方が素早かった。正面でホバリングしている機体に狙いを定め、口を開く。ヘリコプターの方へと飛んでいき、そのまま機体の半分を食いちぎりながら更に上空へと昇った。

それを見たイクスは鮫が獲物を食いちぎる様を思い出した。素早く獲物に食らいつき、一撃で致命傷を与える。大量の出血をする代わりにヘリコプターはもくもくと煙をあげながら落下していった。食いちぎられた残骸も捨てられて地面へと落ちていった。

ゲノム社への追撃はそれだけでは終わらなかった。黒龍が飛び回る軌跡に合わせて紫電が散る。無作為に放たれたように見えた雷だったが、狙いすましたように残りの三台のヘリコプターへと飛んでいった。自然発生し、空から地面へと向かうような雷と遜色ない速度で、黒龍の雷撃はヘリコプターに直撃した。回避すらできずにヘリコプターは音を立てて爆散する。

ゲノム社のヘリコプターが一掃された空で、あざ笑うようにうねる黒龍。動く度に紫の雷が弾け、街のあちこちへと飛んで行った。

余裕を見せる黒龍にゲノム社は捕らえることを諦めたのだろうか。どこからともなく、真っ黒に塗装された、細長い機体が現れて黒龍のすぐ傍を駆け抜けていく。過ぎ去り際、置き土産のようにミサイル弾が黒龍に撃ち込まれた。通り過ぎる時に聞こえた、蜂の威嚇音のような低い嘶き。姿かたちをはっきりと捉えることはできなかったが、あれは戦闘機に違いない。

しかし、空中戦に特化した軍用兵器でも黒龍に傷を付けることは叶わなかった。黒龍の巨体が蛇のようにするりとミサイル弾を避け、ぐるりとその場でとぐろを巻いた。

黒龍が首をもたげると、額に埋め込まれた漆黒の結晶体が妖しい光を放った。禍々しい“音”が流れ出す。この世の憎悪をすべて煮詰めたような、おぞましい叫び声のような“音”だった。より破壊的な“音”に変わっていたが、あの漆黒のマテリアルが奏でていた“音”と同じものだ。

途端に襲い掛かる苦痛。魂を嵐に横殴りにされたような苦しみにイクスは胸を押さえて崩れ落ちる。戦闘機のパイロットもその“音”を聞いてしまったのだろう。ふらふらと危うい軌道を描いたかと思うと、そのまま制御を失って墜落していった。

「マテリアルの力も残ってるのか！？」

黒龍の体で振るわれる物理的な破壊力。そして心を壊すおぞましい“音”。加えて相手は空を自在に動き回ることができて、あれほどの巨体にも関わらず攻撃を当てることすら難しい。

あんなものをどうやって止めればいいのかとイクスは途方に暮れる。

「このままじゃ、ティアが……街を壊しちゃう……！」

空中に敵は居なくなったと言うのに、雷を落とし続ける黒龍を見てタヌタが焦ったように叫ぶ。“音”は止んだが、街の被害は広まる一方だ。

黒龍は憎悪に飲み込まれているようだった。理知的にゲノム社の戦力を削っているが、街の人に対する遠慮はない。黒龍が落とした雷はゲノム社のヘリコプターだけでなく、街中に降り注いでいる。雷に打ち付けられたビルは破片を地面に落下させ、その下に居た人々はパニックになって逃げ惑っていた。

街の人のために、そして何よりティア自身のためにもティアの暴走を止めなければならない。だが止めるための手立てが思いつかない。

イクスが悩んでいると、ふと黒龍の額から生える黒結晶が目に入った。

「……もしかして、額のあれってマテリアルか？それなら……」

「イクスさん？何か思いついたんですか？」

もしあれがマテリアルなら、イクスたちにもできることはある。だが、そのためにはどうにかしてあの黒龍の頭に近づく必要があった。

「あのマテリアルにキュアを使えれば、ティアを人間に戻せるかもしれない……そうすれば暴走も収まるんじゃないか？」

イクスは黒龍の額にある漆黒の結晶体を睨みつけた。黒く塗りつぶされて光を失った瞳のような黒結晶だ。目玉のような形に変わっているが、ティアが持っていた漆黒のマテリアルと同じものに見える。

「確かにそれならティアちゃんを元に戻せるかもしれませんね……！」

「うん……ただ、どう近づくかって問題は残ってるんだよな……」

手をこまねていると、聞き慣れてしまった声が聞こえてきた。

「テメェ！！！何しやがる！！！押すんじゃねぇ、危ねぇだろうが！？」

酒に焼けた声。ゲイスだ。イクスたちの居る屋上にやってきたゲイスはやはり黒服の男たちを後ろに従えているようだった。だが、いつもと違う点が一つあった。いつもならば悠々と肩をいからせて歩いているゲイスが、引っ立てられるように歩かされている。

罪人を連行するようにゲイスを連れているのは神経質そうなスーツの男だ。首元まできっちりとネクタイを締めた男はイクスたちを見つけるなり、不機嫌そうな顔をした。

イクスは男の顔にぼんやりと見覚えがあることに気付く。レイラと侵入した際に施設でゲイスと話していた男だ。イクスと接触はしているが、不意打ちを食らわせて気絶させたため、イクスの顔は知らないはずだ。
「何故一般人がここに居る。即刻立ち退け」

男が不機嫌になったのはやはり気絶させられた恨みではなく、想定外の場所に一般人が居ることに対してだった。
「……ここで何をするつもりだ？」

「フン。我々は治安部隊だ。緊急事態が起きたと連絡を受けて、市民の安全確保のために動いている」
黒龍――ティアを傷付けるつもりだろうか。素直に場所を明け渡していいものか迷うイクス。すると、ゲイスがイクスに気付いて大声をあげた。

「あーーーーー！！テメェ、あのグズに入れ込んでる野郎じゃねぇか！こんなとこまで来やがったのか！」
「何……！？半加工素材の知り合いか……」

にわかにゲノム社の者たちが殺気立った。しまった、とイクスは内心舌打ちをする。戦うには場所が悪すぎる。隠れるところのない開けた場所で、エレノアナとタヌタを庇いながら戦うのは流石に厳しい。

「お前たちの邪魔はしないさ……ここをどけばいいんだろう？」

「あの素材と知り合いと言う割には随分と聞き分けがいいな……まあいい。どうせまたゲイスの早とちりか何かだろう。貴様がこちらに手を出さないのなら、放っておいてやる」

イクスはエレノアナとタヌタを連れて大人しく屋上の端に寄る。貯水ポンプの傍に近づき、ホルスターから抜き放ったままだった銃を構えてゲノム社の出方を窺った。

屋上の縁へと引き立てられながら、ゲイスが喚く。

「おい、どうせまた早とちりってどういう意味だ！！そいつはなぁ！！グズのティアと一緒に俺のマテリアルを――」

「今、お前の泣き言に構っている暇はない。次期幹部だと言うのならば、責を果たせ。あの化け物を制御しろ」

「無茶言ってんじゃねぇ！！あんなのに近づけるかよ！」

どうやらゲノム社はゲイスを使って黒龍となったティアを制御しようとしているようだった。うまく行くとは思えない策だが、もう他に打つ手がないのだろう。

「お前の命令は聞くように躾けてきたのだろう。とっとと行け！」

「テメッ、侵入者に寝かしつけられてたくせにでけぇ口叩いてんじゃねぇ！ふざけんな！」

「貴様………っ！！！」

スーツの男は屈辱に顔を赤くした。ゲイスを屋上の縁へと力いっぱい蹴り出す。

「つべこべ言わずにとっとと行け！！！」

「ヒィッ！？」

放り出されたゲイスのすぐ傍に紫電が落ちる。落雷というよりは、小さな隕石が落ちてきたような衝撃だった。雷が屋上に突き刺さり、煙をあげながらアスファルトを割る。

自分の隣に空いた大穴にゲイスはさっと顔色を悪くした。しかし、ゲイスの存在に気付いた黒龍もぴたりと動きを止めた。憎悪に染まっている瞳が困惑に揺れている、ようにも見える。

黒龍からの攻撃が止んだことにゲイスも気付いた。

「なんだ……？まさか、ビビってんのか……？」

ゲイスが恐る恐る屋上の縁に沿って伸びる手すりに近づいた。手すりを掴み乗り出すと、黒龍が震えて距離を取ろうとする。その反応を見たゲイスがニタリと笑った。

「おいグズ！！！！どこに行こうとしてんだ！！！！」

ゲイスに怒鳴りつけられた黒龍は暴れもせずにただ震えている。調子に乗ったゲイスは笑いながら更に言い募った。

「まだわかんねぇのか！どこに行ったって、化け物のテメェに行き場所なんかねぇんだよ！！！」

恐ろしい黒龍の形に姿を変えたティア。しかし、ゲイスにさげすまれてきた傷が癒えて消え去ったわけではない。ゲイスなど簡単に消し炭にしてしまえる力を得てもなお、ティアはゲイスの言葉に心を縛られていた。

「ティアちゃん……」

エレノアナが震えながらイクスの服に縋った。エレノアナにはきっと、ティアの泣き声が聞こえているのだろう。

「泣かないで、ティアちゃん……」

「テメェは化け物だ！テメェみたいな化け物はどこに行ったって害にしかならねぇ、って何べん言ったらわかるんだ！ああん！？」

「やめて……！ティアちゃんはただ、お父さんに見てもらいたいだけだったのに、どうしてあなたが……！あなたが見てくれなかったら、どうしたらいいのかわからないよ……！」

エレノアナが震える声を張り上げる。しかし、その言葉すらゲイスには届かないようだった。

罵倒を続けるゲイスに、ようやく黒龍が動きを見せた。額の黒結晶を光らせ、“音”が流れ出す。泣きわめくような嵐の“音”に、苦しさを覚えてイクスは体勢を崩した。先ほどのように崩れ落ちるほどの衝撃はない。ただ、息苦しい。

抗いがたい喉の渇きを覚えて、イクスは喉元を抑えた。“音”はさめざめと降りしきる雨のように響いている。ティアが泣いているのだ。飢えたティアの心が痛切な叫びをあげている。

ゲノム社の者たちもイクスと同じように苦しみはじめる。“音”で攻撃されることに慣れていないのか、しばらくすると全員が意識を失った。ただ一人、ゲイスだけが相も変わらずティアを罵り続けている。

ここまで来ても、ティアの言葉はゲイスには響かないのか。

イクスは愕然として拳を握りしめる。頬からは自然と涙が伝っていた。

「……そっか、ティアはボクと同じなんだね」

ぽつりとタヌタが呟く。辛そうに顔を歪めながら、タヌタは潤んでいた自分の目元をごしごしと拭いた。

「タヌタ…………？」

