「これが、ティアなのか……？」

イクスは愕然と呟く。

「ティアちゃんですよ……また、泣いてる……。お父さんに、“置いてかないで”って……」

エレノアナにはマテリアルになったティアの声が聞こえているようだった。轟轟と強い風が吹いている。これがティアの泣き叫ぶ声だとしたら、少女は今どんな思いで施設を食らいつくそうとしているのだろうか。

「エレノアナさんには、あの子の声がはっきりと聞こえるんですね……」

そう言うタヌタもどこか痛ましそうな顔で耳を抑えていた。エレノアナほどはっきりとではないが、ティアの声が聞こえているらしい。

宙に浮くマテリアルに近づいてきたのはイクスたちだけではなかった。黒一色に塗りつぶされたヘリコプターが遠巻きに何台も飛び回っている。ヘリコプターの側面には施設の入口と同じ、遺伝子のような模様が描かれていた。

屋上の縁から見下ろすと、地面もゲノム社で取り囲まれている。埋め尽くすほどではないが、近づこうとする一般市民を追いやれる程度の人数の黒服たちがマテリアルの真下を陣取っていた。

「ゲノム社の機動隊か。かなりの厳戒態勢だな」

「施設の外にもこんなにゲノムの人たちが居たんですね……」

エレノアナがどこか不安そうに空を見上げている。

「ティアを捕まえるために別の部隊が居たのかもしれない。ティアの確保を重要視しているなら、ゲイス一人には任せないだろうし……」

イクスは前にレイラと施設内に侵入した時のことを振り返りつつ、答える。次期幹部を自負しているゲイスだが、実際はさほど評価はされていなさそうだった。ティアがゲノム社にとって重要であるなら、別に動いている部隊があっても不思議ではない。

「なりふり構わず、って感じですね。ティアをそんなに捕まえたいのかなぁ」

鳴り響くヘリコプターの駆動音にタヌタも不安そうに空を見上げていた。

「“多角的な性格”か……」

イクスはこっそりとエレノアナを見た。かつてジェノサイド社の幹部であったフィランダーも随分とエレノアナに執着していた。エレノアナの持つ二面性に目を付けていて、彼女を連れて逃げたイクスをわざわざ自ら追いかけにくるほどだ。優れたマテリアルになりうる素材は本当に貴重なのだろう。それを思えば、多重の人格を持つティアにゲノム社が執着を示すのも理解はできた。

マテリアルが施設を飲み込む、という明らかな異常事態を前にしても機動隊が動く様子はない。むしろ、マテリアルが完全に施設を取り込むまで待っているように見えた。

「どうにかあれを止められれば良いんだが……どうすればいいのか」

マテリアルは空中に浮いており、近づくには飛行手段が必要だった。激しい雷雨が取り巻いているせいで、飛行手段があったとしても易々とは接近できなかっただろう。

だから、イクスたちはそれを眺めていることしかできなかった。

ふと、風の気配が変わる。雷の轟きが響いた。激しい雷が降り注ぎ、目を開けていられないほどの風が吹き乱れる。飛ばされそうになったエレノアナとタヌタをなんとか捕まえるイクス。二人を抱え込みながら、傍にある手すりにしがみついた。

宙に浮かぶマテリアルから黒い光があふれている。目を細めて見上げると、施設の侵食が完全に終わっていた。施設の壁はガラスのような材質に変わり、血脈を思わせる模様が浮き出ている。

どくり、と闇が蠢いた。血脈のような模様の中を稲妻のように黒い影が走り抜けていく。影が走り去った跡は血のような赤色に残った。箱のような形をしていた施設がぐんぐんと縦に伸び、その形を変えていく。上の方は暗雲に消え、全貌が見えなくなってしまう。下の方はつららのように伸び、ワニの顎のような形に姿を変えた。

余ったパーツを捨てるように、施設だったモノの一部が剥がれ落ちる。左右対称に剥がれ落ちた青いマテリアルは形を変え、翼のようなものに姿を変えた。血脈のような模様が再び蠢き、その色を赤に変える。赤くなった部分から黒い染みがあふれだし、青かったマテリアルをあっという間に黒く染め上げた。

施設の窓だったところが真っ赤に染まる。

ぎょろり。

赤い目玉がそこに現れた。施設にあった窓の数だけ、禍々しい赤い瞳が眼を開く。

それが合図であったかのように、ティアのマテリアルであったものは漆黒の光に全身を包まれた。いっそう強い風が吹きすさぶ。

黒い光が晴れると、そこには一匹の禍々しい化け物が浮いていた。

黒く艶やかな鱗に、鋭い牙。太い蛇のような巨体がうねると暗雲がそれに付き従い、雷を迸らせる。顔に当たる部分には目が存在せず、代わりに胴体から首にかけて無数の赤い瞳が生えそろっていた。額からは黒くて大きな結晶体がトサカのように突き出ている。

マテリアルを製造していた施設はティアのマテリアルに飲み込まれ、おぞましい姿をした黒い龍の姿に変わっていた。

「ティア………」

イクスの呟きが聞こえたのだろうか。無数の赤い瞳がイクスに向けられた。憎悪を孕んだ視線に恐ろしいものを感じて、イクスは身を震わせる。

だが、ティアであったこの黒龍が襲い掛かってくるのならば、立ち向かわなければならない。イクスはホルスターから銃を抜き放った。それを止めたのはエレノアナだ。

「待ってくださいイクスさん！！まだティアちゃんの心は残っています！！形は変わってしまったけど、あれはティアちゃんです！！」

「まだ人間の心が残っているのか……！」

この瞬間を待っていたとばかりにゲノム社のヘリコプターが動き出した。六台のヘリコプターが、八面体を描くような陣形でマテリアルを取り囲む。機体の鼻先に取り付けられている円形のパーツが青白い光を帯びた。
バチッ、と大気を焼き切るほどの高圧の電流が発生する。ヘリコプターから流れる電流は線形を描いて互いの機体の鼻先に向かい、ものの数秒で黒龍を囲う八面体の電気檻が生まれた。やはりゲノム社はティアを生け捕りにするつもりらしい。

「ティアちゃん、危ない！！！」

黒龍を弱らせるために更に放たれた電流を見てエレノアナが悲鳴をあげる。逃げ場のない檻の中で、六方から黒龍を狙う雷撃。黒龍が動く前に青白い雷がその黒い鱗にぶつかる。

人間が食らえば消し飛びかねないほどの電圧だ。だが、その程度では黒龍にダメージを与えることはできない様子だった。

何も起きなかったかのように黒龍は平然と滞空している。胴体から生えた目だけが鬱陶しそうに周囲のヘリコプターを睨みつけた。


