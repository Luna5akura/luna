翌日から、イクスたちはダイチを含めて、リョウスケとのバトルに向けて準備を行い始めた。

レイラはキャンピングカーに設置されたコンピュータでユキオのドライブレコーダから送られてきたデータを解析していた

データの解析が進むにつれ、彼らはユキオのドライビングテクニックの圧倒的なスキルに驚嘆した。それに対してリョウスケの車のコーナリングは、まるで車が空を飛ぶかのような余裕を感じさせるものだった。イクスはその光景に目を奪われ、思わず「これはすごい…」と呟いた。

次第に、イクスたちはリョウスケの車がユキオの車を抜けるタイミングが何度もあることに気づいた。しかし、不思議なことに、リョウスケは最後までユキオの車を抜こうとはしなかった。それどころか、後半戦まで追いかけ続けていたのだ。

イクスは首をかしげ、レイラとエレノアナに意見を求めた。

「おかしいだろ、なんでリョウスケさんはわざわざ抜かずに追いかけ続けたんだ？」

レイラは真剣な表情で答えた。

「うーん、もしかしたら、彼はユキオを試していたのかもしれないわね。彼の実力を引き出すために、あえて最後まで抜かずに追いかけ続けたのかも。でも、最後の感じを見る限り、煽っているわけではないし、事故を起こしたのは、あくまでもユキオさん自身かもしれないわ。ほら、ここでリョウスケさんの青い車が避けてる。ここ、避けていなければ、ユキオさんの車は大破してた可能性もあるわ」

エレノアナも熟慮し、追加で意見を述べた。

「私もレイラさんと同じです。リョウスケさんも事故を起こそうとしていなかったようですね」

イクスはその考えに納得し、うなずいた。

「なるほどな……。おそらく、最後で抜かないと、その後に、ユキオさんがまた、抜かそうとしてくるかもしれないという読みだったのだろう」

「ま、でも、映像を見てわかったけど、これはマテリアルの力ね。どう見てもおかしい輝きを放ってるし。データ解説するまでもなかったかも。問題は、どうやって、このドライビングテクニックに勝利するかよね」

「ホント、そこですよね……」

エレノアナは興奮気味に手を上げて言った。

「じゃあ、私がドライバーをやります！勝負を持ちかけたのも私ですし、リョウスケさんに挑むなんて、夢のようです！」

イクスとレイラはエレノアナを見て、顔を見合わせて苦笑した。イクスが言った。

「エレノアナ、確か免許持ってないんじゃなかったっけ？」

エレノアナは照れくさそうに笑いながら、

「そ、そうでした……。すっかり忘れていました……」

レイラはニコニコしながら提案した。

「じゃあ、私とダイチがメカニックを担当して、イクスがドライバーになるっていうのはどうかしら？私たちの組み合わせで、きっとリョウスケに勝てるわよ！」

イクスは少しだけ考え込んだが、レイラの真剣な瞳に映る自分をみて頷いた。

「まぁ、そうなりますよね。レイラさんに運転は任せられないし、オレやってみます。自信ないけど……、みんなで力合わせれば、相手はマテリアルだから、なんとか勝てそうな気もします」

エレノアナも元気よく応援することを約束した。

「頑張ってください、イクスさん！私にも、何か手伝えることがあったら言ってください！」
