仕事以外では誰のいう事も聞かないグレイがミルファのいう事は聞く。
それ故に『猛獣使いのミルファ』等と揶揄する声もあったが、二人には関係なかった。


約束を交わした『いつか』を守る為に、グレイは任務を遂行した。
ミルファを守れるだけの力を手に入れる為に、組織の中でできる事はそれしかなかった。


そんなある日の事だった。
ミルファが訓練中に吐血して倒れたのだ。

身体が強い方ではない事はグレイも知ってはいたが、そこまでとは思っていなかった。

施設にはしっかりとした医療を施してくれる者は在中してはいなかったが、グレイという『猛獣使い』のミルファには特別待遇として医療班を呼んで貰えたのだが、組織所属の医師の診断は想像以上に深刻だった。

「今後一切の激しい運動は難しい」

意識を失ったままのミルファに付きっ切りで居る事を許されたグレイだったが、その言葉を聞いて愕然とした。ミルファの傍に居るように言い残して医療班と出て行った教官たちの事が気になって仕方がない。

真っ白を通り越し青ざめたミルファの頬をグレイは両手で包み込んで「待ってろよ！」と告げると、気配を消して教官たちの後を追った。

グレイに聞かれないように教官たちは医師を、教官の休憩室に連れ込んで話している。身を潜めてグレイは中の会話を盗み聞く。

「じゃあ・・・実験体に？」

グレイは息を殺したまま、固く拳を握る。

「いや、それにしても体力がなさ過ぎて無理ですよ。」
「使い道がないってことですか？」

―使い道って…！？―

グレイも忘れていた訳ではない。
組織にとって自分たちは道具でしかないのだ。道具は壊れれば処分される。
それだけの為に生かされて、壊れにくく殺傷能力の高い道具としての任務を全うすることだけを要求される。

―でも…ミルファは…違う。―

ドアーの向こうで『処分』という言葉を聞いた瞬間、グレイは飛び出していた。

教官たちが咄嗟に医師を囲み、グレイから守るように身構える。
間違いなくグレイが怒り狂い危害を加えてくるだろうと考えての事だった。

それだけグレイとミルファの関係が強い事を教官たちは認識していたが、ミルファに出会わなければそもそもグレイは今そこに立ってはいない。

突然居なくなる子供たちが何処に消えているのかさえ、グレイは興味を持たなかった。
今までもこうして、身体的能力がない者は実験に回されてきたのだろうし、彼らにとっての『使い道』に入れない者は処分されてきたのだろう。

グレイ自身がどういう理由で売られて来たのかについての興味は今でもないが、今生かされている組織について知らなすぎた事は反省しなければならない点だと思った。

言葉を使うより拳を先に出していたグレイだったが、その時は違った。


銃まで持ち出し構えている教官たちに向かって、直角に腰を折り懇願した。

「ミルファの分も…あたしが仕事するから！二人分働くから…ミルを安静に過ごさせてあげて欲しい！頼むから！！」

鼻に掛かった震える声が、独特のタバコの臭いが漂う部屋に響き渡った。


それが『死神グレイ』の誕生の瞬間となる。


組織はグレイの懇願を受け入れ、グレイは組織にただ従った。
どんなに危険な仕事であっても、組織の指示通りに遂行し理由は聞かず言われるがままに動くだけに徹した。

もう、夢を見る事もない。
ミルファの為なら喜んで『死神』の看板を背負うと決めた日からまるでミルファと出会う前のグレイに戻ったように、浅い眠りと体力維持のための食事のみになっていった。

月に一回程度だったが、仕事の合間を使ってグレイはミルファに会いに行く。

ミルファは壁の外にあるゲノム社が運営している医療機関に移されていた為、仕事を終えたあとに顔を見せる程度しか会えなくなっていたが、施設に居る時よりは赤みを帯びていく頬を見ると安心できた。

『マシュマロ』みたいだと思ったあの柔らかい肌の白さは、異常だったことを改めて感じる。

ミルファはグレイの知らない所で無理をして訓練を受け続けていたのだろう。
それでもグレイの隣にいる時だけは、そのしんどさを隠していたのだろうか？

グレイもまたミルファの顔を見られた時には『死神』の仮面を剥がして、二人で過ごした時間のグレイに戻れていた。

ミルファに今までどれだけ無理をしてきたのかを聞いても、ミルファは陰りのない笑顔を浮かべる。

「ううん。グレイと居られる時は楽しいから。無理なんてしてなかったよ！元から身体が弱くて、両親が亡くなって親戚に引き取られたんだけど…。身体が弱いから…」

（だから、売られた）

とは、ミルファは言わない。

誰かを悪く言ったりはしない。
「医療機関で良くしてもらっているのか？」とグレイが聞いても「うん。とても良くしてもらっている」と答える。

一つだけ違う事は、以前のようにミルファからグレイの近況を聞こうとはしない事と、グレイから自分の今を話さなくなっただけだった。

二人で笑いあえた頃のようには、もう出来ない…。

グレイは『死神』と言われるくらいには、血にまみれてしまっているから。

それでもグレイが顔を出し帰る時には、必ず二人は小指を絡めた。誰が何処で監視しているか分からない為、言葉は使わずに二人でした約束を確認し合うかのように。

「ミル。また来るから！」
「うん！！待てる！！」


それが３年前…。

ミルファが医療機関に入院をして１年位は面会できていたのに、ある時を境に会う予定だった日にミルファの体調がよくないから今は難しいと言われた。その後に回復したと連絡がある時は遠方に行かされていて会えず、そんな事を繰り返すようになっていた。

ミルファに会いたいと談判しても『二人分の仕事量をこなす約束を果たせ』と突っ返され、直ぐに仕事の話に戻された。与えられた任務を文句なくこなしてきたと詰め寄った時には、今は静養していると動画の映像を見せられた事もあった。

しかし、もう３年も会えていないのは流石におかしい。

グレイが組織から下された仕事として、女優ミラを誘拐する為に訪れたリゾート地カイポールにてイクスと一戦を交えた。『（彼らを）処分しろ』という命令ではなかったが人工マテリアルの可能性を覆してくる生身の人間であるイクスと刀を交え、グレイの中で何か沸々とまた知らなかった感情が上がった。それを何と表現するのかは解らない。

―あいつなら、あたしを壊してくれるのだろうか…？―

そうなる前にやらなければならない事がある。

グレイはイクス達の動向を気にしているゲノム社の本部に赴き、幹部たちに報告をした後にミルファについて切り出した。

やはりと言うべきなのか、いつものようにのらりくらりと話を逸らされはしたがグレイの我慢も限界に来ていた。

グレイの今にも襲いかかってきそうなオーラにあてられた幹部二人は、今までとは〝何か″が違うと感じたのか邪険な返答を控えて話し出したが、信じるつもりはなくただグレイは帯刀したまま幹部を睨んでいた。

これまでにも何回かそういう事はあった。
ミルファは現在医療機関を退院させて空気のいい場所で静養させていると言ったかと思えば、その場所はまた追って連絡するからと流され、もう１年以上が過ぎる。

動画を見た時も２本とも服を替えただけで背景もカメラの位置も変わっておらず、わざとらしく昼なのにカーテンが閉められ外が見えないようになっていた。

３年前に病室を訪れた時にミルファが言っていた。

「この窓から中庭が見渡せて、花が綺麗なの。そろそろシロツメクサの季節だから、また冠作りたいな。」

ミルファのピンクの髪には、シロツメクサの冠が似合う。
でも、グレイはどんなにミルファに教えてもらっても花を編むが苦手で作れなかった。だから中庭に降りてシロツメクサを１輪、茎を長めに摘んで、それを輪にしてミルファの指に絡めてやった。

「タンポポの指輪みたいにはいかないけど、元気になるまではこれで我慢しろ！」

ただ傍に居てあげる事さえできず、ミルファに花の冠を作ってやることもできない自分が嫌で、グレイはミルファの顔を真正面から見る事はできなかった。
しかしミルファは二人で過ごしていた頃のように、キャキャと騒いで喜んでくれた。


カーテンを閉めていた理由は同じ時期に撮影されたからだとグレイは疑い、それを指摘すると『自分は知らない。医師たちに任せている事だ』と話をはぐらかされて以降は動画を見せてくることも無くなった。


グレイは静かに同じ言葉を幹部たちに投げつける。

「ミルファは今何処にいる！」


幹部たちは顔を見合わせ、顔がこけてる白髪の方が口を開いた。

「医療部に連絡を入れて確認すると言ってるだろ？」

「それは、前にも聞いた！」

グレイが刀に手を掛ける。すると白髪の隣に座っていた小太りの幹部が両手を出して「まぁまぁ」とでも言いたげに眉を歪めた。

「こちらとしても、働けない者を養っている状況なのは解るだろう。身を寄せるにしても、長期での受け入れ先が無くてね。でも、グレイが頑張っていることはちゃんと伝えているし、向こうからの報告はあるから…とりあえず、落ち着いて。数日中には連絡を入れるから！」


こういう会話にもそろそろ飽きてきた。

その数日中に次の仕事が来て、結局は流される。グレイは「解った」と言い残し部屋を出た。

グレイが出てきて長い廊下を帰って行くのを確認した警備員が室内の幹部に無線で連絡を入れるのを待ち、瞬時に気配を断ったグレイは扉の前に立っている２人の警備員の首元を静かに打ち気絶させた。

警備員からの内線を受け取り幹部はすっかり安心したように口が軽くなった。

「そろそろ、限界だろうか。」

先に口火を切ったのはしゃがれているハイトーンの声。
白髪の頬がこけた方の幹部だった。

ドアの隙間に聞き耳を立ているグレイは殺気にならないように気配を消したまま、胸糞悪いとばかりに歯を食いしばる。

「ミルファをマテリアルにしてから３年も経っているのにしつこいですね。これだけ会わせなければ、流石に忘れると思っていましたが。」


―ミルファを…マテリアルに！！！！―

「でもまぁ、知らないでいれば…グレイだって動きようも手の出しようもな…」

グレイのストッパーはその小太りの男の言葉で一気に崩壊し、会話を中断させる形でドアーを蹴破って室内に飛び込んだ。

帰ったはずのグレイが再び現れた事に二人の幹部は脂汗をかいて震えていたが、椅子に座ったまま動かない。否、余りの迫力に動けないでいた。


「どういう事だよ！！てめぇら！！！答えろ！！！！」


グレイの恫喝に震えながらも緊急通報のボタンを押そうと小太りの男が腕を動かすと、瞬時にグレイが目の前に現れた。

正確に言えばデスクの上に飛び乗りしゃがんでその男の顔を覗き込んで、刀に手を掛けている。

少しでも動けば、腕を切り落とす事も首を切る事もできる。

「ミルファは何処にいる！！マテリアルにされたミルファは何処だって聞いてんだよ！！」

「…い、あ、そのぅ私たちがしたわけでは…」

グレイが刀を抜きかける。

「ほ、ほ…本当に、知らないんだ。もう、３年前の話だし！何処か…金払いの良い所に売った…かも…なぁ？…と、闘技場とか…。恐らくだが…」

小太りの男の生臭い息を顔面に浴びながら、『それだけ聞ければもうお前らに興味はない』とばかりにグレイは入り口のドアまで飛びのいた。

「ミルが居ないなら、出て行くぜ。あんたらに貸しはない！」

グレイはそれだけ告げると荷物をまとめてゲノム社を後にしたのだった。


ミルファと過ごした頃には外に出る事が夢のまた夢のような気がしていたが、ゲノム社の幹部をはじめ警備員さえもグレイを止めようとはしなかった。

既に管理できるレベルにグレイが居ないのだ。

『死神』の名をもつ暗殺者を飼いならせていたのは、その足枷になるミルファという人質があったからである。

しかし、身体の弱いミルファを囲い続けてくれる程組織は甘くない。

そもそも子供を買い付けてきて戦闘員に育て上げ、人が原料のマテリアルを量産しているような組織がまともなはずはない。


解っていた事でもグレイはミルファの名を出されれば、従わずにいられなかった。


―だから知りたくなかったんだ。何も知らずに道具でいれば…―


グレイは道端に咲いていたタンポポを１輪摘むと、小指に巻き付けた。

「ミルファ…約束は守るから…！絶対だ！！」


知らなかった頃になんて戻れないし、グレイは戻りたいとも思わなかった。


ゲノム社の白髪の幹部の方が血相を変えて室内を闊歩している。

「良かったのか！グレイを手放す様な事になって…俺たち大丈夫か？」

小太りの男はグレイに脅され肝が冷えた様とは別人のように、悠然とチェアにもたれかかる。

「慌てなさんな！グレイは育ち過ぎた悪魔だ。人の姿では扱いにくいが…マテリアルに出来たら、最高級品に化けますよ？フフフフフ‥‥」



―・・・レ・・・ィ・・・！グ・・・レイ！！―

音がしている。

春の風のように爽やかで、夏の木漏れ日のように暖かい。でも、雪のように冷たい雫。


グレイは一度だけミルファを泣かせたことがあった。

ミルファは訓練がどんなに辛くてもグレイの傍に居る時は笑顔だったが、グレイが仕事から帰りささくれだった心を吐露した時の事だった。

「なんでお前が泣くんだよ！」

「だって、グレイが…泣かないから…！」

ミルファは自分の為にではなく、グレイの為に泣いていた。

「自分の事を道具だなんて言わないでよ！それは、グレイが望んだことじゃない！」

