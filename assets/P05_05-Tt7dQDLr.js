ホテルに戻ったイクスたちは気分転換も兼ねて、遅い晩御飯を取っていた。ホテル内にあるエスニカルなレストランに入ったのだが、メニュー表に書かれている文字を見てイクスとエレノアナは首を傾げる。
パッタイ、バインミー、ホッケンミー。
メニューの名前を見ても何の料理かまったく分からない。

「あら、フォーがあるのね」

レイラだけは慣れた様子で頼みたい料理をすぐに決めていた。レイラの言葉を聞いて、エレノアナも目を輝かせる。

「あっ、フォーは食べたことあります！お母さんが家で作ってくれたことがあるんです！」

「へぇ！前から思ってたけど、エレノアナちゃんの家は料理上手ね」

「お母さんの趣味が料理だったから……私も一緒に良く作ってました」

「イクスくんは何頼む？」

レイラに聞かれて、イクスは改めてメニュー表に目を落とした。

「ええっと……このオススメにしてみます」

腹が膨れれば何でも良いか、と適当に目についた物を頼むことに決めるイクス。なにやら麺と揚げ豆腐を特性ダレにつけて食べる料理らしい。

「オススメってなあに？……って、げっ。ブンダウマムトムじゃない……」

「苦手なんですか？」

レイラが珍しく顔を曇らせる様子にイクスは目を瞬かせた。

「マムトム——あ、タレのことね——の臭いがちょっと独特で、私は苦手かなぁ。原料はエビらしいんだけど……」

臭いが独特と言ったレイラの言葉は正しかった。注文をしてしばらくすると厨房から強い海鮮の臭いが漂ってきて、これのことかとイクスは納得する。一度嗅いだら忘れられない、強烈な臭いだ。
エレノアナが何故か目を輝かせて厨房の方に熱い視線を送る。

「あっ！ほんとうにエビっぽい……かは分かりませんけど。おさかなとか、そういう類いの臭いですね！ピィちゃんはダメみたいです」

ピィ、と弱弱しい声をあげながら、エレノアナの背中と椅子の間にハピネスが潜り込む。隠しそびれた青い尻尾がふるふると震えている。
そんなハピネスを気にする様子もなく、料理が机まで運ばれて更に臭いが強烈なものになってもエレノアナは好奇心を抑えきれない目で皿を見つめていた。

「見た目は普通なんですね！」

「ああ……エビのスープと言われれば、そんな感じだな」

スープのようにも見えるタレの中に浮かぶ、赤いなにかをつつくイクス。この赤い切り身がエビかどうかはわからないが、臭いは間違いなく海鮮物だ。
ひとまずタレに豆腐をつけて食べてみる。表情が変わらないまま、もぐもぐと咀嚼するイクスに、レイラが恐る恐る尋ねた。

「ど、どう……？はじめて食べる人はだいたい怯むんだけど……」

「全然平気ですよ。確かに臭いは強いですけど、クセになりそうな感じです」

「そっかぁ……私は、臭いで、ダメだわ………」

「エレノアナも食べてみるか？」

「はい！食べてみたいです！」

あまりにも興味津々にエレノアナが見つめてくるので、タレと豆腐を取り皿に取り分けるイクス。
エレノアナは取り皿を受け取り、豆腐をスプーンに乗せてそうっと口元に近付けてから、覚悟を決めたようにぱくっと口に放り込んだ。直後、驚いたようなエレノアナの両目が見開かれる。

「すごいです！強烈です！こんなの食べたことないです！」

「エレノアナちゃん、嬉しそうね……？」

「はい！初めて食べる味です！」

「食べ物の好き嫌いがないのは……良いことね……」

独特の臭いを楽しむようにうきうきとしているエレノアナを見て、とうとうレイラががくりとうなだれる。

「えっと………すいません」

珍しく弱り切ったレイラの様子に、イクスは申し訳ない気持ちになってきた。無意味と分かっていながら、皿を自分の方にギリギリまで引き寄せてレイラからできるだけ遠ざける。

「ううん、イクスくんは食べたいものちゃんと食べて……。これは私の問題だから…」

そう言いながらも、レイラは食事が終わるまでしょんぼりとした様子で自分の皿をつついていた。



---



「ううん、胃もたれしそう……」

食事が終わった後もレイラはげんなりとしていた。まだマムトムショックから立ち直れていないらしい。

「レイラさんにもダメなものってあるんですね。ちょっと意外です！」

「そう言うエレノアナちゃんは意外と平気なのね……」

「山育ちですから！山菜とかにアクが強いものとかもありますし……。ちょっとくらいインパクトが強くても、美味しいものはいくらでもあります！」

「山育ちとかそう言う問題かしら……？」

「もっとすごいのだと、近所のおじさんが蜂を育ててたので、たまに——」

「あっ、却下。詳しい話は今はやめて……」

レイラはそのまま弱弱しく机に突っ伏した。すかさずハピネスがレイラの頭の上に乗り、悠々と毛づくろいを始める。それでも動かないレイラは回復にもう少しかかりそうだ。

「それにしても、今回は早く解決しましたね」

自分が頼んだ料理のせいでレイラが沈んでいるので、少しばかり後ろめたい気持ちでイクスは話を変えた。
ミラとのしこりは残ったものの、マテリアルの解放はできた。一応、これでイクスたちの当初の目的は果たせたことになる。

「でも、ミラちゃんを狙ってる人たちがまだ居るんですよね……？」

「占い師のソフィアが言ってた件ね。ミラのホテルで会った怪しい二人組覚えてる？ミラを狙ってる奴らって、あいつらのことじゃないかしら……」

机に突っ伏したまま、ごそごそと懐から情報端末を取り出すレイラ。

「気になったから、あの時に念のため——」

少し立ち直った様子のレイラが何かを言おうとした時だった。
激しい振動がレストラン全体を揺らした。地震の揺れに似ているが、揺れと共に聞こえてきた音が嫌な予感を感じさせる。

「……爆発？」

「イクスくんもそう思う？」

勢いよく顔をあげるレイラ。レイラの頭の上に乗っていたハピネスが短く鳴きながらバサバサとイクスたちの周りを飛び回る。何かを警告しているかのような動きに、三人は表情を引き締めた。
レストランを急ぎ足で出て辺りを見回してみると、遠目に火が出ている建物が見えた。燻る黒い煙がイクスたちの宿泊しているホテルの元まで流れてきている。

「あれって……ミラちゃんの泊ってるホテルじゃ……」

「まさか、あの時の奴らが爆発を……？」

ミラの安否が気になって、爆発地の方に向かうイクスたち。すでに野次馬が大勢集まってきていて、混沌とした雰囲気を漂わせていた。駆けつけた消防隊員や治安維持隊がやかましく怒鳴る声があちこちから上がる。
何人かの怪我人がホテル内から運び出されているようだった。ミラは無事だろうか。あちこちを見回して、ミラの姿を探していると、ふと見覚えのある人影がイクスの目の端に止まる。
路地裏の方に向かって、よろよろと歩く一人の男が居た。雪だるまのようなシルエットの上にちょことんと乗せられた赤いキャップ。
息も荒く、うつろな足取りが不審者のようだが、あちこちに擦り傷を負っているところを見ると不信感よりも心配が先だった。

「確か……ええっと、フォアグラ」

ミラのホテルに乗り込んできたファンの男だ。ミラが呼んでいたあだ名を口にしながら男の方に近寄るイクス。

「大丈夫か？」

「あ、貴方たちは……！」

今にも崩れ落ちそうな男の体をイクスが支えると、男ははっと顔を上げた。
助けてください。
か細い声で男はイクスたちに訴えた。

「ボクじゃあダメでした……ボクは何もできなくて……」

「いったい何があったんだ？」

男は悔しそうにぐっと奥歯をかみしめる。

「突然、ミラちゃんの部屋が爆発して……そしたら見慣れない奴らがたくさん現れて……そのまま……ミラちゃんが……連れていかれた……」

声を出すのが精一杯と言った様子で、男はがくりと地面に崩れ落ちた。
