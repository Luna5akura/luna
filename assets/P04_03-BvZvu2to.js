追われていたことに対する焦りもなく、逃げ切れたことに対する安堵もなく、氷のように冷たい横顔を眺めていたイクスはゆっくりと目を瞬かせる。冷めた印象の女性だった。だが、ふと時々エレノアナの手元をちらっと見る視線だけは気遣わしげだった。
エレノアナの手の中には小ぶりな籠があり、中には青い小鳥が一匹蹲っている。ゴミ山の傍で倒れていた青い毛玉の正体だ。弱っていて、傷だらけだが命に別状はなさそうだった。今はすやすやと籠の中で眠っていて、エレノアナに微笑ましげな表情で見守られている。

「小鳥さん、さっきちょっとご飯も食べたんですよ。たぶんもう大丈夫だと思います」

「良かったな。しかし、なんであんなところに鳥が……？」

しげしげと小鳥を覗き込むイクス。スズメやカラスならともかく、街中でこんな鮮やかな青色の鳥を見たことはない。元々どこかで飼われていた鳥だろうか。

「その子は……捨てられたんじゃあないかしら。最近、ペットとしての鳥はほとんど禁止になってしまったから」

名乗ったきり黙り込んでいたシキがぽつりと言った。アイスブルーの瞳が僅かに揺れている。

「禁止になったって？」

尋ねられ、シキは小鳥を見つめていた視線をゆっくりとレイラに向けた。

「……“不要物”よ」

「不要物……あっ、そう言えば、あそこの門にそんなことが書いてあったわね。確か、“不要物退出ゲート”……だったかしら」

イクスもその門に見覚えがあった。レクトシティの外れの方に積まれていたゴミ山の傍にひっそりと佇んでいた門だ。

「レクトシティのルールは知っているでしょう。レクト市長がいらないと言ったものはいらないの。彼がいらないと言った瞬間、それは存在価値をなくしてゴミになる。不要物退出ゲートは……あの門はそういうものを外に捨てるためのゴミ箱よ」

「えっ！？じゃあ、この子は……」

エレノアナが息を飲んで自分の手元に視線を落とした。

「ゴミよ。少なくとも、レクトシティの中ではね」

シキは顔色も変えずにそう言った。ショックを受けたようにエレノアナが小鳥を見つめたまま固まってしまう。レイラもさすがに眉をひそめて、少し不機嫌そうに腕を組みかえる。

「市長さんが鳥全般を禁止にしたってこと？流石に横暴じゃない？」

「ちょっと前にカラスの糞を踏んだらしいわ。それで、鳥は都市の景観損ねるから原則禁止になったの。ペットとしての鳥も、万が一に逃げ出したら都市を汚すからやっぱりダメ。ニワトリみたいな“益のある”鳥だけね、許されているのは」

ほんのわずかにシキの口角が笑みの形に持ち上がる。口調は淡々としていながらも、皮肉っぽい侮蔑がその表情に見え隠れしていた。

「不満を持つ人はいないの？」

「さあ。いるんじゃあないかしら。でも、市長の考えにあからさまに反抗すると自分が不要物になってしまうもの。本心を表立って言うことはないでしょうね」

「横暴なのね」

「怖いのよ、きっと」

シキのその言い方をイクスは不思議に思った。

「……怖い？」

「自分と違う考え方をする他人が怖いの。自分の知らないことを知っている人も、そういう人間は怖がるわ。見知っていた世界に急に異物が入りこんだら驚いてしまうでしょう。急に自分の家のドアを他人に蹴り破られた気分になるのでしょうね」

随分と乱暴な例えだと思いながら、イクスは首を捻る。
どちらかと言えば、逆ではないだろうか。自分が他人と違う考えであることが怖い、という感情なら多少なりとも覚えがある。恐怖と言う程強くはないが、できる限り人とぎくしゃくしないように余計な言葉は避けようと言う気分にはなる。

「……じゃあ、シキはレクト市長の家のドアを蹴り破ったのか？」

「………どういうことかしら？」

「いや、レクトタワーの奴らに追われていたみたいだったから……」

「そうね、不要物としてね。人間は一応、“不法入都市者”だったかしら。どうでもいいけれど……」

レクト市長の意見に逆らえば、不要物扱いされると言ったのはシキ自身だった。彼女の口ぶりから、市長のやり方を面白く思っていないだろうことは感じられた。
