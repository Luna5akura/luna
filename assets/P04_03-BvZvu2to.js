「“幸福の王子様”から取ったんです。ツバメさんと王子様の出会いは涙だったから……」

幸福の王子様は心優しい王子の銅像と一匹のツバメの物語だ。とある町に通りかかったツバメは銅像の王子が泣いていることに気付く。王子は町で貧しさに苦しんでいる人たちを見て、心を痛めて泣いていた。王子のことを放っておけなかったツバメは、動けない銅像の王子の代わりに宝石や金箔を町人に届けてやる。ツバメが運ぶ宝石や金箔は元々王子を飾っていたもので、町人を助けようとすればするほど王子の銅像はみずぼらしくなっていった。それでも王子は町人たちを愛し、何度でも救おうとし、ツバメもそんな王子を助けた。

「……その名前」

シキが言いづらそうに目を伏せた。

「はい」

「……小鳥がすぐ死んじゃいそうよ」

子ども向けの童話ながら、幸福の王子様は中々に悲劇的な終わりを迎える。王子の願いを叶えるために町に残り、暖かい土地に渡らなかったツバメは最後に寒さで凍え死んでしまうのだ。

「え？あっ！？あ、青い鳥です！幸せの青い鳥から取った名前なんです！」

「それならまあいいけど……」

シキとイクスたちが助けた小鳥は無事にハピネスと名付けられた。
