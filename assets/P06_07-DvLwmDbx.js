今こうして死線を潜り抜け、互いに信頼し合える仲間とだからなのか！

どれも正解な気もするが、はっきりと分かるのはイクスが選んだ道は間違えてはいないという確信が持てるという事だった。

「レイラさん酷いなぁ～！」

『MYSTIQUE』店内が笑いに包まれた。


ミルファに髪を弄られ「やめろよ！」とじゃれていたグレイだったが、イクスの方を向いた時に一瞬真面目な表情を浮かべた。

「人を生かす最高のスナイパーなんだから、闇に乗じていても構わねぇだろ？」

ミルファがグレイに抱きつきながらイクスに微笑みかけて来た。
レイラもウィンクをしてそれに乗じる。
エレノアナが『うんうん』と大きく首を振って、イクスの元に駆け寄ってくる。

「多分ですけど、太陽の光だけでは生き物は疲れちゃいます。夜の休息も、雨の恵みも生きていくうえでとっても大切なんですよ！」

それぞれに役割がある事を改めて感じられる。

それが『人を生かす』と表現された事に、なんとも言えない感情が湧いてくる。

「ああ。そう居られるように…頑張るよ！」

イクスはその場にいる全員に声を掛ける。

グレイは直ぐに視線を逸らしたが「そうしてくれ…」と答えた。

隣にいるエレノアナは真っすぐとイクスの言葉を受け止め「はい！！」と頷いた。

ミルファは「素敵なお友達ができたね」とグレイに微笑みかけるが、グレイは「ちげぇよ！」とミルファの髪をくしゃくしゃにして誤魔化している。

レイラはただグラスを傾けながら、大人の微笑みを零すに留めていた。


再び和やかな時間が訪れると、今度はグレイからミルファにサンドイッチを食べさせてやりたいという提案がなされ、レイラもお腹が空いたと騒ぎだした。

ドランクからも店の食材を提供しする申し出を受け、エレノアナは作る為にどうしても必要なものがあると言い、キャンピングカーに取りに出かける。

それが何であるのかが解るレイラとイクスは視線を絡めて「あれよね？」「あれですね！」と納得していた。

