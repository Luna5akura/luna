イクス達を乗せたキャンピングカーは、水しぶきを上げながら走行していた。

目指す先は、今回の地下闘技場コロシアムで行われるクオドロトーナメントについての情報を流してくれたドランクの店だった。

雨脚はどんどん激しさを増している。


マテリアルを探す旅をイクス・エレノアナ・レイラの三人で始めてから、色んな土地で色んな人と出会ってきたが、その中でBar『MYSTIQUE』の現オーナードランクの事は信頼できる。

コンスタントに連絡を取り合っているのも理由の一つではあるが、彼自身もイクス達とは別の方法でマテリアルにされてしまった人についての情報を集めている仲間の一人だからだ。

大切に想う相手をマテリアルにされた人だから分かり合える絆は、常に行動を共にしなくても深くあるものだろう。

イクスとレイラが手負いの状態で駆け込める安全な場所として、迷うことなく連絡を入れられたのも互いへの信頼があってこそだと感謝していた。

小さなランタンの明かりが見えた時には、ハンドルを握っていたイクスの手が少しだけ緩んだ。

ゆっくりとハンドルを回して曲がりくねった石畳の洒落た街並みを走行させていると、故郷にでも帰って来たような気がする。

レンガ調の建物に囲まれた石畳の道も冠水していた。

徐行しているにも関わらず、キャンピングカーの大きなタイヤが通るたびにそれと分かる水しぶきの音が車内にも聞こえる。

コロシアムから『MYSTIQUE』までは２時間もあれば到着できる距離なのだが、天候もさることながら此処までイクスとグレイが交互に運転をしてきた為に３時間以上かかってしまった。


当初は車内の空気は重かった。

トーナメントにファイターとして出場し、一戦交えた後に巨大化したモンスターとも戦ったレイラは体力だけではなく精神力もかなりすり減っていて「イクス君。ごめん～！」と告げたままソファーに寄りかかり立てなくなった。
エレノアナは暖かいコーヒーを入れ動き回って介抱してくれていた。

その傍を今回はキャンピングカーで留守番をさせられた、青い小鳥のハピネスが相手にしてもらおうと必死にエレノアナについて回っていた。

コロシアムを脱出するまでは張りつめていた気持ちが一気に緩んだのか、それともあるべき日常に戻れた安堵感なのか…。
特に口にすることはないけれど、それぞれがそれぞれの持ち場とばかりに動いたが、グレイはその状況に直ぐには馴染めないようだった。

計画通りにマテリアル『スカイブルーの瞳』の奪還には成功した。

しかし結果的に成功したというだけで、予想外な事が多すぎたとイクスは思う。

レイラは「結果良ければすべてよし！」とエレノアナが淹れたコーヒーを飲みながら笑んでいたが、情報量が多すぎるからか流石のイクスも憔悴を隠せなかった。


それでも、取り合えずは行ける所まで。
なるべくコロシアムから離れた場所へと車を走らせている間の事だった。

ワイパーをフル回転させても前方が霞んで見えるフロントガラスを凝視していたイクスの後方から、笑い声が聞こえて来てイクスはバックミラーを確認するがすぐには何が起こったのか解らない。

その後で、エレノアナが嬉しそうに運転席の横に身体を捩らせて入り込んでくる。

「コーヒーをグレイさんも喜んで下さいました！」
ピ～ピ～～！！

「そうかぁ…それで…」

自分も早くエレノアナが淹れてくれたコーヒーに癒されたいと気持ちがはやるが、イクスは前方から視線を逸らさずに運転を続けた。

「イクスさんの分もあるので！」
ピィィイイ～！！

エレノアナに合わせてハピネスも自己主張をしている。

「・・・フゥ・・・」

イクスは自然と軽いため息を躍らせた。

特にイラついている訳ではないが今回は一筋縄ではいかない事が多すぎる事件であった事と、肉体的に痛めつけられた部分がうずき平静を装うのが精一杯なのだ。

それでも、エレノアナとハピネスのコントのようなやり取りには癒される。

「コーヒーは後で貰うよ。ありがとうエレノアナ！」

イクスはエレノアナとハピネスしかいないのだと思いながら声を掛けたが、予想外の声で返答が即座に返ってきた。

「もう少し進んで大通りに出ろ。そしたら、運転代わってやる。」

その声はグレイだった。

実際に見ては居ないイクスだったが、エレノアナのコーヒーを飲んだ時にもトーナメントの休憩中にほぼ強引にサンドイッチを食べさせられた時に見せたような、驚きと感動を現しただろうことは想像に難くない。

しかしイクスへの声は堅く冷静なままを装っているようで、思わず息を漏らして微笑んだ。

「な…んだよ！お前！！今、笑いやがったな！！！」

何故かグレイという人間の新たな一面を見たようで、可愛く思えた。

「別に…笑ってはないけど…。
でも、グレイが一番酷くやられてるからもう少し休んでていいよ。」

今だからこうして和んだ気持ちでいられるが、教官モンスターと対峙した時に受けたグレイのダメージは普通の人間ならばとっくに召天していてもおかしくないレベルだった。

それでもキャンピングカーを取りに行っただけではなく、エレノアナの話ではコロシアムの控室に置いたままにしてあった愛刀を取りに行って今に至るというのだから、イクス達の普通と思う観点で彼女を見るべきではないのだろう。

しかし感情的に怒りを露わにしたグレイを見たイクスは、もう特別とは思っていない。

「お前らと一緒にすんな。鍛えられ方がちげぇんだよ！こんな大雨で事故られても困んだよ！さっさとコーヒーとやらを飲んで来い！」

それがグレイなりの優しさなのかもしれないとイクスは感じ、それから交互に運転をすることになったのだ。

イクスがグレイと運転を代わって、やっとありつけたエレノアナのコーヒーは雨に濡れた四肢の先まで染み入ってくるように優しくて最高だった。

グレイもそれを味わい大袈裟に感動したのだろう。
でもそれが、彼女にとっては大袈裟に表している訳ではない事をイクス達は知っている。

多くは語らないが、グレイが生きて来た世界には無かったのだろうし、何よりもエレノアナの作る物に感動しない者は居ないのだと身内贔屓ではなく感じられる。

運転しながらも『スカイブルーの瞳』と名付けられたマテリアルを握り締めたままのグレイの背中を見つめて、イクスはコーヒーを飲み干していた。

「お替わり入れましょうか？」

エレノアナが声を掛けてくる。

「ありがとう。じゃあ、あと一杯だけ貰おうかなぁ」
「はい！！」

二人掛けのソファーを独占するようにレイラが寝息を立てていた。

目の前のテーブルにはレイラ専用のコーヒーカップがあるので、既に飲み切って一休みしているのだろう現状は解るが、レイラが人前で無防備に寝るということ自体が珍しかった。

それだけ疲れているという事なのだろう。

コロシアムの支給品であるコスチュームのまま座りこみ、立てない状況でコーヒーだけ煽ってすぐに寝てしまったレイラを気遣いエレノアナが毛布を掛けたのだろう。

イクスは心の底からそんなレイラに『お疲れ様』と言いたい気持ちを二杯目のコーヒーと共に、飲み下した。


目的地であるBar『MYSTIQUE』に着くまでは気は抜けない状況は続く。


コロシアムの惨状とグレイと共に逃げている事も含めて、いつ何が起こるのかは常に気を張っていなければならない。

イクスがマテリアルを人に戻す旅を続けてきて学んだことでもあった。


イクスがハンドルを任されてアンティークな街並みに入った頃。
慎重に車を進める車内ではレイラが起き出して服を着替え、グレイとも何やら揉めている声が聞こえていたが何が起こっているのかは…想像は出来た。

『あ～多分…』

イクスが苦笑いを浮かべていると案の定、レイラが運転席にいるイクスの横に身体を乗り出させてきた。

「ちょっと聞いてよイクス君！！
グレイったらね、私が服を貸してあげるって言ってるのに私の服は着たくないとか言うのよ！！」

「あ～まぁ、そうでしょうねぇ」

イクスの想像を裏切らないレイラだったが、そんな他愛もない事が愛おしい。

それがまた気に食わないとばかりにレイラが身を乗り出してくるが、そんな状況に安堵した。

色々な事がありすぎて、既に懐かしくなってしまっているBar『MYSTIQUE』。

「あ～早く、フロイライン・ルージュが飲みたいなぁ～！」

レイラが口角を上げて気まぐれな猫のように話題を変える。
Bar『MYSTIQUE』の元オーナーから引き継がれている名物オリジナルカクテルなのだが、レイラは相当気に入っているのだろう。

「そうですね。でも…今日はノンアルコールにしてもらった方が良いと思いますよ？」

少し休んだからといって、こんな短時間に万全に戻るはずがない。
アルコールを飲むのはまだ早いのではないかとイクスは心配して答えたつもりだったが、すかさずレイラが反論してくる。

「イクス君はまだお子ちゃまねぇ！い～い？戦士が勝利したらまずはお酒で祝杯するのが流儀ってものなの！
アルコール消毒って言うでしょ？こういう時こそ、飲みたくなるものなの！分かった？？」

「はぁ…まぁ、そうなんでしょうけど…」

レイラの圧にイクスが折れるのは毎度の事ながら、レイラの身体の事を気遣って言ったつもりが『お子ちゃま』呼ばわりされると流石のイクスも苦笑を深めるのみに留めた。

「イクス君。有難うね…」

耳元でそう囁きレイラが戻って行く。


イクスはハンドルを強く握り直した。
感謝を述べたいのは自分の方だ。常にイクスを信じて先行して動いてくれるレイラには頭が下がると同時に、尊い仲間だと断言できる。

Bar『MYSTIQUE』を今は故郷のようだと言えるのも、レイラとエレノアナのおかげでもあった。

会いたくなかった昔の自分を知っている知人ビリーと出くわした場所としての認識を遥かに超え、匿って貰える仲間がそこで待っていると胸を張って言い切れる。

知人ビリーには無理だと馬鹿にされてもジェノサイド社に入社を果たしていたイクスだったが、そんな保身よりも『守らなければならない』『見過ごす事はできない』と自分の中に生まれた『あるべき事』に気付かせてくれたエレノアナとの出会いで、イクスは大きく変わった。

他ならぬグレイだって、そうなのではないか？
否、そうなのだろうと此処にいる誰もが疑っていないのも解る。

だからこそ、激しく打ちつけてくる雨に視界が歪んでも目的地まで全員を無事に連れて行く気持ちを再確認するように、イクスはハンドルを握り直した。


ステンドグラスの丸いランプが見えた。
それと分かるように明かりが点いている。


店の前にキャンピングカーを横付けすると、直ぐに店のドアーが開く音がした。
ドランクが到着を待っていてくれたのだろう。

大きな傘を広げ、直ぐに店内に入るようにジェスチャーしているのが解る。

レイラがキャンピングカーを降りて再会を喜ぶように抱きついて行ったが、ドランクはそれより早く店内に入るように促してくれているようだ。

イクスは任を無事に果たせた安心感ですぐには立ち上がれなかった。

「お疲れ」

そんなイクスに一番に声を掛けてくれたのは意外にもグレイだった。

雨音に交じって「早くこっちよ～」とレイラの声がすると、視線を合わせる事なく降りていく。

共に戦いに興じた仲以上に運転を任せ合い此処まで辿り着けたことへの感謝は、言葉以上に重いものだった。

「ありがとう。グレイ！！」

イクスもグレイの背中に声を掛けるが、グレイはなんの反応も示さずに降りて行った。

「照れてらっしゃるんですね！」

後からエレノアナが顔を出して微笑んでいた。

エレノアナがそう思うならそうなのかもしれない…そんな説得力がある。
マテリアルの情報があればあちこちに出向くようになってから、コロシアムと『MYSTIQUE』は長距離には入らない距離だったが、イクスにとってはとても長く感じるドライブだった。

なかなか立ち上がる気力が湧かないでいると、エレノアナが手を差し出してきた。

「さぁ、イクスさんも行きましょ！！」
「ああ！」

エレノアナの華奢な手を借りて何とか立ち上がり、二人で店に向かう。

ドランクが気を利かせて全員が入るまで傘をさして待ってくれていたので、そんなに濡れる事なくイクスとエレノアナそしてハピネスが当たり前のように店内入って行く。

全員の入店を確認してドランクは勢いよく頭を下げ謝罪してきた。

「ごめんなさいね！まさか…こんな危険な目に合うなんて…」

言葉を詰まらせているドランクだったが、すかさずレイラがフォローするように感謝を述べ、概要を説明して納得してもらうように促してくれた。

色々あったにせよ、一つは人工マテリアルでありもう一つのマテリアルの奪還が成功したのはドランクの情報のおかげだった事。
