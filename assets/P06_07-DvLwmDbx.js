エレノアナがいつものように、先にハピネスに野菜とパンを差し出す。
「ピーちゃんが一番贅沢だね」
ミルファは嬉しそうにハピネスに背中を撫でていた。

イクスには攻撃的なハピネスが、ミルファに撫でられる事を全く嫌がっていない。
『ミルファは猛獣使いなのか？』

そんな事を思いながらグレイに視線を移すと、イクスが考えていた事を読み取ったのかグレイに睨まれた。
「んだよ！その目は！！施設でも…言われてたよ！
猛獣使いのミルファって…こいつは、すげえんだよ！」

それを聞いてレイラが楽しそうに笑っていた。
「尻に敷かれてるってことか～ミルファちゃんすごっ！」

グレイはレイラに向かって「しめる！！」と脅すが、レイラは「あ～怖い」と言いながら逃げている振りをして笑っていた。

誰もそこにいるグレイを『死神』とは、もう呼ばないだろう。

「やるなら、イクス君を進呈します～」

レイラがふざけてイクスに振ると、グレイが本当にイクスの方に進んでくる。
「なんで、俺なんですか～」

「言い出しっぺだから？」
レイラが舌を出しておどけて見せた。

「いや、言ってないし…！」
「そういう目で見ただろうが！！」

グレイは柔らかい表情のままイクスに詰め寄って行った。


料理が出来る間じゃれ合う店内の事には全くお構いなしに、エレノアナとミルファは二人で互いの料理の話に夢中になっている。

「美味しい…これどうやって作ってるの？」

味見をして声を上げたのはミルファだった。

「後でこっそり教えますね！ミルファちゃんのこのスープも最高です！後で教えてください！」
「勿論！…こっそりね！」

エレノアナ特性マスタードの作り方はレイラでさえ教えて貰えなかったが、ミルファになら教えるつもりらしい。

イクスがレイラに「悔しいですか？」と、いつもとは反対の茶化しを入れてみたが、レイラはさらっと「私は食べる専門でいいの！」とカクテルを飲み干した。

「やっぱり最高～！ドランクマスターお替わり！」
「飲み過ぎないでくださいよ…」

イクスが声を掛けると、カウンターの方でも声がした。

「うっめぇ～～～！！お替わり！！！」

その声はグレイだった。
イクスを追い回すのに飽きたグレイも、カクテルを飲み干していたのだ。

