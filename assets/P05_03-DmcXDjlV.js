ミラの頭の上にちょこんと青い小鳥が乗っている。ハピネスだ。もこもこの羽毛を膨らませて、呑気に毛づくろいをしている。

「ぴ、ピィちゃん！その人はダメです！女優さんの……人気スターの頭の上にピィちゃんが……！？」

「イクスさん、レイラさん！見て！！ピィちゃんが頭の上に乗ってくれたの！」

飼い主であるエレノアナが慌てて下ろそうとしているが、ミラ自身は嬉しそうにはしゃいでる。
頭の上のハピネスを落とさないように慎重に、運転席に居るイクスとレイラが見やすいようにじりじりと近付いてきた。

「あら、可愛いわね！」

レイラが微笑ましいものを見るようにくすくすと笑った。

「……鳥、好きなのか？」

大女優の頭の上に鳥。この状況にイクスはそれ以上、なんと言っていいのかわからなかった。

「うん！だってかわいいもん！」

ミラはイクスの戸惑いに気付いた様子もなく、満面の笑顔を浮かべている。女優という印象はかき消え、まるで普通のあどけない少女のようだった。

「あと、それとね……鳥は、私が女優になるきっかけなの！」

「そうなんですか！？」

そうっとハピネスを下ろそうとしていたエレノアナが驚いて、動きを止めた。ミラの頭に伸ばすべきか迷っていたエレノアナの手が中途半端なところで止まる。

「えー、知りたい？」

「はい！知りたいです！」

前のめりになって大きく頷くエレノアナ。エレノアナのキラキラと期待に揺れる瞳を真正面から見たミラは更に笑みを深めた。

「えー、どうしよかっかなー？」

わざとらしく迷うように口元に人差し指を当てて、悩むそぶりを見せるが、口元が少しにやけている。

「ふふふっ、やっぱ教えなーーーーい！」

「えーーーっ！」

あからさまにショックを受けるエレノアナを見て、ついにミラが吹き出す。

「ごめん、冗談！実はね——」

「あっ、目的地に着いたわよ～」

ミラが何事かをエレノアナに囁こうとしたそのとき、ちょうどキャンピングカーが停車した。
フロントウィンドウの向こうに、フェンスで囲まれた岬が見える。岬の先端の真上には大きな満月が浮かんでいた。



