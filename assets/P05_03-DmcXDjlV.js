響き渡ったミラの悲鳴に、イクスは慌ててそちらを振り返った。
何があった？ミラと、エレノアナは無事だろうか？
瞬時にイクスの脳内を駆け巡った緊張感に対して、振り返った先の光景は平和そのものだった。

「きゃーー！見て！！ピィちゃん！！」


