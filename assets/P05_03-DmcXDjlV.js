雲一つない夜空には大きな満月が浮かんでいる。今夜が満月の晩。ピンク色のマテリアルが運命の人を指し示す夜だ。
レイラのキャンピングカーにミラも一緒に乗り込み、イクスたちは四人で縁結びの岬を目指していた。

「それでね！」

ミラが声を弾ませて何かをエレノアナに説明しようとしている。年頃が近いからか、ミラとエレノアナはすっかり打ち解けた様子ではしゃぎまわっていた。

