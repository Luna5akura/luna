「エレノアナちゃん……」

「大丈夫です。一緒に、やりましょう！」

重なった自分の手とエレノアナの手を見下ろすミラ。緊張に強張っていたミラの表情が、少しだけ緩んだ。

「……………がんばるぞ、ファイヤー」

「え？」

ぽつりとミラが小さくこぼした。

「私のおまじない。昔……近所のお兄ちゃんが口癖みたいに言ってたおまじないでさ。私が怖くなったり、不安になったとき……いつも私の手を握って、そう言ってくれたの。今のエレノアナちゃんみたいに。なんか、思い出しちゃった……」

とても小さな声でミラはありがとう、とエレノアナに囁きかけた。そして覚悟を決めたように空を見上げる。
