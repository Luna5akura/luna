「あ………」

最初は淡い光だった。月光を受けたマテリアルからピンク色の光がこぼれだす。それは徐々に輝きを増し、岬の真下にある海面を輝かせるほどの強い光に変わった。水面に映った青い満月がマテリアルの光と混ざり合い、紫まじりの美しいグラデーションに染まっていた。
そして気付けば、“音”が流れていた。
何か雨音のような“音”だった。
ぽろん、ぽろろん。張りつめた糸をしなやかな指が小さくはじく。そのたびに、ガラス細工のように繊細で美しい音色が鳴る。暖かく包み込んでくれる広大な海のような、優しい音色が誘うように流れる。
