少女らしく小首をかしげて微笑むエレノアナ。だがその姿がいつもよりどこか大人びているように見えて、イクスはどきりとさせられた。
思わず茫然とエレノアナを眺めてしまう。

「でも、絶対大丈夫って私が保証します！だから、やりましょう……ミラちゃん！」

「………うん。分かった」

エレノアナの穏やかな表情に背中を押されたようにミラがようやく歩き出した。胸元に提げていたマテリアルを手に握り、岬の先端へと慎重に進んでいく。
