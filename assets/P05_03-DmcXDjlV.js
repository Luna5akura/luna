キャンピングカーを出ると、涼しい夜風と優しい波音がイクスたちを出迎えた。森の奥にある岬には人の気配はなく、耳をすませば虫の声が微かに聞こえてくる。

「昼間はここまでバスが出てるから、観光客がすごいらしいけど……さすがに夜は誰もいないわね」

「確かに、森を通りますからね」

レイラとイクスがなんでもない話をしながら、岬の先端へと向かう。マテリアルを使うなら、満月に一番近いあの場所が良いだろう。
ミラを促そうとして振り返ったイクスは、目を瞬かせた。思った以上に離れた場所にミラが居たからだ。キャンピングカーから出てすぐのところで、何故か立ち尽くしている。ミラの表情には不安のようなものが浮かんでいた。

「ミラちゃん、どうかしましたか？」

エレノアナはミラの隣で、ミラが動くのを待っているようだった。そんなエレノアナをミラが、どこかすがるような目で見つめた。

「えっと……ここまで来といて、変な話だけど、なんか……緊張しちゃって……」

おずおずと言いだしながらも、すぐに俯いてしまうミラ。

「“運命の人”……わかっちゃうんだ、って……。変だよね……。自分で知りたかったのに、なんか……急にちょっと怖くなっちゃったっていうか……」

「自分の人生が変わっちゃいそうで怖い……ですか？」

エレノアナの声色はとても柔らかく、暖かい。だというのに、傍で聞いているイクスですらはっとする程に鋭い言葉だった。じくじくと胸が傷むのに、なぜだかその傷みに救われたような気持ちになる。そんな不思議な鋭さがあった。

「エレノアナちゃん……？」

「大丈夫ですよ。自分でも想像していなかったくらい、世界は変わってしまうかもしれないけど。でも、それは絶対悪いことじゃないです。幸せになるために、変わるんですよ。だから、大丈夫」

スキップするような軽やかな足取りで、エレノアナが岬の先端に向かって数歩進む。少しだけ進んでから、ミラに手を差し伸べた。

「“運命の人”って、そういうものですから！だから、行きましょう！」

自信に満ち溢れたエレノアナの笑みをミラは呆然と見ていた。

「……エレノアナちゃんは、自分の運命の人を知ってるの……？」

「うーんと、それは……」

ふと、エレノアナがイクスの方を見た。——こっちを見たかのようにイクスには見えた。
そのまま軽快な足取りでエレノアナは岬の先端まで駆けて行った。イクスとレイラの横をすり抜けて、一足先に岬の先端にたどり着くエレノアナ。満月の真下で青いワンピースを翻しながら、少女は振り返った。
そしてゆっくりと、自分の口元に人差し指を当てる。

「ヒミツです」


