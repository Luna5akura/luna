「そういえばそうですね。こうしていると、急に自分が歳を取った気になります」

なんでなんでしょうね、とイクスはぼやくように呟く。

「あら。イクスくんも十分若者でしょ～？あっ、もしかしてミラちゃんにエレノアナちゃんを取られて拗ねてるとか？」

「いえ、そういうわけじゃ……ないと思うんですけど……。ただなんか、うーん。眩しくって」

「あはは、なにそれ！——まあ、でも私もちょっと学生時代のこと思い出しちゃった」

ふと黙り込むレイラ。ハンドルを回しながら、フロントウィンドウの向こうに広がる夜の森を静かに眺めている。
レイラの学生時代か、とイクスは考え込んだ。きっと今も昔も変わらないのではないかと思う一方、レイラがどんな学生だったのかいざ具体的に思い浮かべようとした途端にぼんやり浮かんでいたイメージが溶けるように消えてしまう。
出会う前のエレノアナのことは勿論、ジェノサイド社に入社する前のレイラのことも実はイクスは良く知らない。もしかしたら関心を抱いたことさえ、今まであまりなかったかもしれない。
仲間のことだから気になっても良いはずなのになんでだろう、とイクスは思わず目を瞬かせた。

「ねえ、イクスくん」

「えっ……は、はい」

少しぼんやりしていたイクスは慌ててレイラの方に視線を戻した。レイラは相変わらず前方の景色を見つめている。

「イクスくんは“運命の人”って信じる？」

「え？」

ちらっとイクスの方を見たレイラの赤い眼差しに思わずどきりとする。

「ど、どうでしょう……運命……」

どきりした心臓をごまかすようにイクスはもごもごと呟いた。レイラはイクスのそんな様子に気付いて、いつものようにくすくすと笑う。いつもと違うのは、笑われているイクスだけではなくレイラの頬も少し赤いことだ。

「あー、こんな話題あんまり慣れないわね」

珍しくレイラが照れている様子にイクスも思わず小さく笑ってしまう。

「そうですか？運命の『赤い』糸って言うからレイラさんにぴったりだと思いますけど」

「おっ、イクスくんも言うじゃない！」

バシッ！と思いほか強い力でレイラに背中を叩かれ、驚くイクス。完全にイクスの方に体を向けたレイラがまったくフロントウィンドウの方を見ていなかったからだ。

「ああっ、ちょっとレイラさん前見てください、前！」

「大丈夫、大丈夫！」

明るく笑いながら運転に戻るレイラ。幸いとキャンピングカーはどこにもぶつからずに順調に進んでいるようだった。

「いやー、ミラちゃんの話聞いてさ。“運命の人”なんて本当に居るのかなーって考えちゃって」

「ああ……。マテリアルが運命の人を指し示す、ってことは本当にあるんじゃないですか？」

「うーん。ってことなのかなぁ、やっぱり」

少し不満そうにため息を吐くレイラ。

「なんか嫌そうですね……」

「決められた未来だった、っていうのをマイナスに捉えちゃうのよね。なーんかしゃくに障る、って言うか」

「定められた未来……」

「もう決まっちゃってるものだからー、って言われたらひっくり返したくならない？」

「俺は……」

決まっているものをひっくり返したい。レイラらしい考え方だと思いながら、自分はどうだろうか、とイクスは考える。運命というものを自分が否定的に捉えている気はしなかった。

「俺は、“約束”って感じがして意外と好きかもしれません」

「約束？」

「はい。会った時から、知らない間に交わしてた約束を果たす……みたいな。運命の赤い糸って小指に結ばれてる、って言いますし。指切りと同じ指ですよね」

「ふぅん？」

レイラの声色が変わった気がして、イクスは顔を上げた。考えているうちに俯いていたらしい。レイラは意外な物を見るような、少し驚いた表情でイクスを見ていた。
イクスが顔を上げたことに気付くと、ふわりとその表情が笑みの形に和らぐ。

「イクスくんらしいと思うわ」

「そう、ですかね」

「うん、とっても」

向けられた笑みがあまりにも暖かくて、イクスは照れ臭い気持ちで頬を指で掻いた。

「じゃあさ！イクスくんにもし運命の人が居るとしたらどんな人だと——」

レイラがイクスに何かを問いかけようとしたとき。

「きゃーーーーーーーっ！！」

ミラの悲鳴がキャンピングカーに響き渡った。



